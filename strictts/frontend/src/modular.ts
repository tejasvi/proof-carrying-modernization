// Modular output (`--modular OUTDIR`): one Lean module per function, so that a proof about a
// function depends only on that function's IR and its callees' signatures, and its .olean
// survives edits elsewhere in the program.
//
//   NS/Types.lean        the type table `TT` and the field lists `«C».fields` of the classes
//   NS/Refs/<f>.lean     `«fRef» : FunRef args ret := ⟨idx, "f"⟩` (imports the prelude only)
//   NS/Globals/<g>.lean  `«g_x» : GRef t := ⟨idx, "x"⟩`
//   NS/Externs/<e>.lean  `«pkg:f_ext» : ExtFun := ⟨"pkg:f", args, ret⟩`, one per signature of an
//                        external function called by `extern` nodes (imports StrictTS.Proof.Extern)
//   NS/Defs/<f>.lean     `«fDef» : FunDef TT` and `«f_call_of»`, the call rule over every program
//                        that has `«fDef»` at `«fRef»`'s index; imports Types and the Refs,
//                        Globals and Externs that the IR mentions
//   NS/Program.lean      `mainBlock`, `program`, `«f_lookup»` (`program.funs[«fRef».idx]? =
//                        some «fDef»`) and `«f_call»`
//
// Indices are kept stable by an index map (JSON, rewritten on every run): a function or
// module-level variable keeps its index and module name (an external signature its abbreviation
// and module), new ones are appended, and the slot of
// a removed function holds a stub that panics when called, so adding or removing a function
// changes no other function's Refs or Defs module. Files are written only when their text
// changes, and the generated modules of removed functions are deleted.
import * as fs from 'fs';
import * as path from 'path';
import { showTy, showTys } from './ty';
import { FunInfo, GlobalInfo } from './ir';
import { ProgramIR, Emitter, ExternSig, q, typeTableLines, funRefLines, globalRefLine, funDefLines, mainBlockLines,
  externAbbrevLine, argList } from './emit';

const HEADER = '/- Generated by the StrictTS frontend (modular output). Do not edit. -/';
const FORMAT = 'strictts-index-map/1';
/** The definition at the index of a removed function. */
const REMOVED = q('removed function');

/** An index: the function or module-level variable `name` (its Lean name) and its module. */
interface Slot { name: string; module: string; removed?: boolean }

/** An external signature: `name` is its key (extern name and types), `abbrev` the name of its
 * `ExtFun` abbreviation (numbered per extern name `ext` in order of first appearance, as in the
 * single-file output). */
interface ExtSlot extends Slot { abbrev: string; ext: string }

/** The index map: position in `funs` = index in `Program.funs`, in `globals` = heap cell. */
interface IndexMap { format: string; namespace: string; funs: Slot[]; globals: Slot[]; externs: ExtSlot[] }

export interface ModularOptions { outDir: string; indexMap?: string; eval?: boolean }

export interface ModularResult {
  /** directory of the modules (`OUTDIR/NS`) */
  dir: string;
  indexMap: string;
  modules: number;
  written: string[];
  deleted: string[];
}

/** A wrong option or index map (reported without a stack trace). */
export class ModularError extends Error {}

export function validNamespace(ns: string): boolean {
  return /^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$/.test(ns);
}

function readIndexMap(file: string, ns: string): IndexMap {
  if (!fs.existsSync(file)) return { format: FORMAT, namespace: ns, funs: [], globals: [], externs: [] };
  let m: IndexMap;
  try { m = JSON.parse(fs.readFileSync(file, 'utf8')) as IndexMap; }
  catch (e) { throw new ModularError(`${file}: ${(e as Error).message}`); }
  if (m.format !== FORMAT || !Array.isArray(m.funs) || !Array.isArray(m.globals))
    throw new ModularError(`${file}: not an index map (format ${FORMAT})`);
  if (m.namespace !== ns) throw new ModularError(`${file} is the index map of namespace ${m.namespace}, not ${ns}`);
  m.externs = m.externs ?? [];
  return m;
}

/** Indices of `names`: existing slots keep theirs, new names are appended. Module names are
 * the Lean names, made unique ignoring case (for case-insensitive file systems). */
function assign(slots: Slot[], names: string[]): Map<string, number> {
  const idx = new Map<string, number>();
  slots.forEach((s, i) => idx.set(s.name, i));
  const taken = new Set(slots.map(s => s.module.toLowerCase()));
  for (const n of names) {
    if (idx.has(n)) continue;
    let m = n, i = 2;
    while (taken.has(m.toLowerCase())) m = `${n}_${i++}`;
    taken.add(m.toLowerCase());
    idx.set(n, slots.length);
    slots.push({ name: n, module: m });
  }
  const live = new Set(names);
  for (const s of slots) {
    if (live.has(s.name)) delete s.removed;
    else s.removed = true;
  }
  return idx;
}

const externKey = (x: ExternSig) => `${x.name} ${showTys(x.args)} ${showTy(x.ret)}`;

/** The slots of external signatures (`sigs` in order of first appearance): existing ones keep
 * their abbreviation and module. */
function assignExterns(slots: ExtSlot[], sigs: ExternSig[]): Map<string, ExtSlot> {
  const byKey = new Map(slots.map(s => [s.name, s]));
  const taken = new Set(slots.map(s => s.module.toLowerCase()));
  for (const x of sigs) {
    const key = externKey(x);
    if (byKey.has(key)) continue;
    const k = slots.filter(s => s.ext === x.name).length + 1;
    const abbrev = `${x.name}_ext${k > 1 ? k : ''}`;
    const base = abbrev.replace(/[^A-Za-z0-9_]/g, '_').replace(/^(?![A-Za-z_])/, '_');
    let m = base, i = 2;
    while (taken.has(m.toLowerCase())) m = `${base}_${i++}`;
    taken.add(m.toLowerCase());
    const s: ExtSlot = { name: key, module: m, abbrev, ext: x.name };
    slots.push(s);
    byKey.set(key, s);
  }
  const live = new Set(sigs.map(externKey));
  for (const s of slots) {
    if (live.has(s.name)) delete s.removed;
    else s.removed = true;
  }
  return byKey;
}

function moduleText(ns: string, imports: string[], body: string[]): string {
  return [HEADER, ...imports.map(m => `import ${m}`), 'set_option maxRecDepth 100000',
    'open StrictTS StrictTS.Frontend', '', `namespace ${ns}`, '', ...body, `end ${ns}`, ''].join('\n');
}

/** A name in a doc comment. */
function docName(s: string): string { return s.replace(/`/g, "'").replace(/-\//g, '- /'); }

export function emitModular(p: ProgramIR, opts: ModularOptions): ModularResult {
  const ns = p.namespace;
  if (!validNamespace(ns)) throw new ModularError(`namespace ${ns}: expected dot-separated Lean identifiers`);
  const dir = path.join(path.resolve(opts.outDir), ...ns.split('.'));
  const mapFile = path.resolve(opts.indexMap ?? path.join(dir, 'index.json'));
  const map = readIndexMap(mapFile, ns);
  const funIdx = assign(map.funs, p.funs.map(f => f.leanName));
  const globalIdx = assign(map.globals, p.globals.map(g => g.leanName));
  const funModule = (f: FunInfo) => map.funs[funIdx.get(f.leanName)!].module;
  const globalModule = (g: GlobalInfo) => map.globals[globalIdx.get(g.leanName)!].module;
  // imports, sorted by module name
  const refMods = (xs: Iterable<FunInfo>) => [...xs].map(funModule).sort().map(m => `${ns}.Refs.${q(m)}`);
  const defMods = (xs: Iterable<FunInfo>) => [...xs].map(funModule).sort().map(m => `${ns}.Defs.${q(m)}`);
  const globalMods = (gs: Iterable<GlobalInfo>) => [...gs].map(globalModule).sort().map(m => `${ns}.Globals.${q(m)}`);

  // the IR, one emitter per function so that each records the external signatures it calls
  const defs = p.funs.map(f => {
    const fem = new Emitter();
    return { f, text: funDefLines(fem, f).join('\n'), externs: [...fem.externs.values()] };
  });
  const mem = new Emitter();
  const main = mainBlockLines(mem, p);
  const sigs = new Map<string, ExternSig>();
  for (const x of [...defs.flatMap(d => d.externs), ...mem.externs.values()])
    if (!sigs.has(externKey(x))) sigs.set(externKey(x), x);
  const extSlot = assignExterns(map.externs, [...sigs.values()]);
  const externMods = (xs: Iterable<ExternSig>) =>
    [...new Set([...xs].map(x => extSlot.get(externKey(x))!.module))].sort().map(m => `${ns}.Externs.${q(m)}`);

  const files = new Map<string, string>();
  files.set(path.join(dir, 'Types.lean'), moduleText(ns, ['StrictTS.Frontend.Prelude'], typeTableLines(p)));
  for (const g of p.globals)
    files.set(path.join(dir, 'Globals', globalModule(g) + '.lean'),
      moduleText(ns, ['StrictTS.Frontend.Prelude'], [globalRefLine(g, globalIdx.get(g.leanName)!), '']));
  for (const x of sigs.values()) {
    const slot = extSlot.get(externKey(x))!;
    files.set(path.join(dir, 'Externs', slot.module + '.lean'),
      moduleText(ns, ['StrictTS.Frontend.Prelude', 'StrictTS.Proof.Extern'], [externAbbrevLine(slot.abbrev, x), '']));
  }

  // the functions and module-level variables that a piece of emitted IR mentions
  const funByRef = new Map(p.funs.map(f => [q(f.leanName + 'Ref'), f]));
  const globalByName = new Map(p.globals.map(g => [q(g.leanName), g]));
  const mentions = (text: string) => {
    const funs = new Set<FunInfo>(), globals = new Set<GlobalInfo>();
    for (const m of text.matchAll(/«[^»]*»/g)) {
      const f = funByRef.get(m[0]); if (f) funs.add(f);
      const g = globalByName.get(m[0]); if (g) globals.add(g);
    }
    return { funs, globals };
  };

  for (const { f, text: def, externs } of defs) {
    files.set(path.join(dir, 'Refs', funModule(f) + '.lean'),
      moduleText(ns, ['StrictTS.Frontend.Prelude'], [...funRefLines(p, f, funIdx.get(f.leanName)!), '']));
    const used = mentions(def);
    used.funs.add(f);
    const ref = q(f.leanName + 'Ref'), name = q(f.leanName + 'Def');
    files.set(path.join(dir, 'Defs', funModule(f) + '.lean'), moduleText(ns,
      [`${ns}.Types`, 'StrictTS.Proof.CallRule', ...refMods(used.funs), ...globalMods(used.globals), ...externMods(externs)],
      [def, '',
        `/-- The call rule of \`${docName(f.name)}\`: in every program that has this definition at the`,
        `reference's index, a call runs its body. -/`,
        `theorem ${q(f.leanName + '_call_of')} (I : Impl) (P : Program TT) (hf : P.funs[${ref}.idx]? = some ${name})`,
        `    (vs : Vals TT ${argList(f)}) :`,
        `    callFun I P ${ref} vs = applyLam I P ${name}.lam .nil vs :=`,
        `  callFun_lookup I P ${ref} _ _ hf vs`, '']));
  }

  const funAt = new Map(p.funs.map(f => [funIdx.get(f.leanName)!, f]));
  const globalAt = new Map(p.globals.map(g => [globalIdx.get(g.leanName)!, g]));
  const n = map.funs.length;
  const prog: string[] = [];
  if (map.funs.some(s => s.removed)) {
    prog.push('/-- The definition at the index of a removed function (indices are stable): a call panics. -/');
    prog.push(`def ${REMOVED} : FunDef TT where`, '  name := "removed function"', '  args := tys[]', '  ret := .num',
      '  lam := .sync [] rfl', '    .nil', '');
  }
  prog.push(...main, '');
  // the function list by its suffixes, so that each lookup fact has a constant-size proof
  // (`rfl` on `program.funs[i]?` walks the list: quadratic in the number of functions)
  prog.push('/-- `funs_k`: the function list from index `k` on. -/');
  prog.push(`def funs_${n} : List (FunDef TT) := []`);
  for (let i = n - 1; i >= 0; i--)
    prog.push(`def funs_${i} : List (FunDef TT) := ${funAt.has(i) ? q(funAt.get(i)!.leanName + 'Def') : REMOVED} :: funs_${i + 1}`);
  prog.push('');
  prog.push('def program : Program TT where');
  prog.push('  funs := funs_0');
  const gs = map.globals.map((_, i) => globalAt.has(i) ? showTy(globalAt.get(i)!.ty) : '.undef');
  prog.push(`  globals := ${gs.length ? '[\n' + gs.map((t, i) => `    ${t}${i + 1 < gs.length ? ',' : ']'} -- ${i}`).join('\n') : '[]'}`);
  prog.push('  main := mainBlock', '');
  if (n) prog.push('/-! Lookup facts and call-unfolding lemmas: a call of a top-level function runs its body. -/', '');
  for (let i = 0; i < n; i++) {
    prog.push(i === 0 ? 'theorem funs_drop_0 : program.funs.drop 0 = funs_0 := rfl'
      : `theorem funs_drop_${i} : program.funs.drop ${i} = funs_${i} := drop_succ_of_drop_eq funs_drop_${i - 1}`);
    const f = funAt.get(i);
    if (!f) continue;
    const ref = q(f.leanName + 'Ref'), name = q(f.leanName + 'Def'), lookup = q(f.leanName + '_lookup');
    prog.push(`theorem ${lookup} : program.funs[${ref}.idx]? = some ${name} := getElem?_of_drop_eq funs_drop_${i}`);
    prog.push(`theorem ${q(f.leanName + '_call')} (I : Impl) (vs : Vals TT ${argList(f)}) :`);
    prog.push(`    callFun I program ${ref} vs = applyLam I program ${name}.lam .nil vs :=`);
    prog.push(`  ${q(f.leanName + '_call_of')} I program ${lookup} vs`, '');
  }
  const progImports = [`${ns}.Types`, 'StrictTS.Proof.CallRule', ...defMods(p.funs), ...globalMods(p.globals),
    ...externMods(sigs.values())];
  let progText = moduleText(ns, progImports, prog);
  if (opts.eval) progText += `\n#eval runMain ${ns}.program "${ns}"\n`;
  files.set(path.join(dir, 'Program.lean'), progText);

  // write what changed; delete the generated modules of removed functions and variables
  const res: ModularResult = { dir, indexMap: mapFile, modules: files.size, written: [], deleted: [] };
  for (const [file, text] of files) {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) continue;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    res.written.push(file);
  }
  for (const sub of ['Refs', 'Defs', 'Globals', 'Externs']) {
    const d = path.join(dir, sub);
    if (!fs.existsSync(d)) continue;
    for (const ent of fs.readdirSync(d)) {
      const file = path.join(d, ent);
      if (!ent.endsWith('.lean') || files.has(file)) continue;
      if (fs.readFileSync(file, 'utf8').split('\n', 1)[0] !== HEADER) continue;
      fs.unlinkSync(file);
      res.deleted.push(file);
    }
  }
  const slots = (ss: Slot[]) => ss.length === 0 ? '[]' : `[\n${ss.map(x => '  ' + JSON.stringify(x)).join(',\n')}\n ]`;
  const mapText = `{\n "format": ${JSON.stringify(map.format)},\n "namespace": ${JSON.stringify(map.namespace)},\n` +
    ` "funs": ${slots(map.funs)},\n "globals": ${slots(map.globals)},\n "externs": ${slots(map.externs)}\n}\n`;
  if (!fs.existsSync(mapFile) || fs.readFileSync(mapFile, 'utf8') !== mapText) {
    fs.mkdirSync(path.dirname(mapFile), { recursive: true });
    fs.writeFileSync(mapFile, mapText);
  }
  return res;
}
