"""Generate tests/proof/F64EvalCheck.lean: closed-number evaluation (StrictTS.Proof.F64Eval) against the
host's IEEE doubles. Each case states `lit a OP lit b = lit r` with r computed by Python (binary64,
round-half-even; `%` is fmod) and closes it with `simp only [ts_sym]`; a wrong value leaves a goal.
usage: python3 tools/f64eval/gen_check.py N SEED > tests/proof/F64EvalCheck.lean"""
import math, random, struct, sys

def lit(x):
    """The translator's literal form (frontend/src/core.ts f64Lean)."""
    if math.isnan(x): return "F64.nan"
    if x == math.inf: return "(F64.inf false)"
    if x == -math.inf: return "(F64.inf true)"
    if x == 0 and math.copysign(1, x) < 0: return "(F64.zero true)"
    if x == int(x) and abs(x) <= 2 ** 53:
        return f"(F64.ofNat {int(x)})" if x >= 0 else f"(F64.ofInt ({int(x)}))"
    b = struct.unpack(">Q", struct.pack(">d", x))[0]
    neg = b >> 63; be = (b >> 52) & 0x7FF; frac = b & ((1 << 52) - 1)
    man = frac if be == 0 else frac + (1 << 52)
    e = -1074 if be == 0 else be - 1075
    return f"(F64.mkFin {'true' if neg else 'false'} {man} ({e}))"

def rnd(r):
    k = r.randrange(6)
    if k == 0: return float(r.randrange(-1000, 1000))
    if k == 1: return r.randrange(-10 ** 6, 10 ** 6) / r.choice([2, 4, 10, 100, 1000, 3, 7])
    if k == 2: return r.uniform(-1, 1) * 10.0 ** r.randrange(-30, 30)
    if k == 3: return struct.unpack(">d", struct.pack(">Q", r.getrandbits(64)))[0]
    if k == 4: return r.choice([0.0, -0.0, 0.5, 0.25, 0.1, 0.2, 0.3, 1.5, -2.5, 2.0 ** 53, 2.0 ** 53 + 2, 5e-324])
    return r.choice([math.inf, -math.inf, math.nan, 1e308, -1e-310])

def js_rem(a, b):
    if math.isnan(a) or math.isnan(b) or math.isinf(a) or b == 0: return math.nan
    if math.isinf(b): return a
    if a == 0: return a
    return math.fmod(a, b)

def js_div(a, b):
    try: return a / b
    except ZeroDivisionError:
        if a == 0 or math.isnan(a): return math.nan
        return math.copysign(math.inf, a) * math.copysign(1, b)

def safe(f, a, b):
    try: return f(a, b)
    except OverflowError: return math.copysign(math.inf, 1.0)

ops = [("+", lambda a, b: a + b), ("-", lambda a, b: a - b), ("*", lambda a, b: a * b), ("/", js_div), ("%", js_rem)]
n, seed = int(sys.argv[1]), int(sys.argv[2])
r = random.Random(seed)
print(f"""/- Generated by tools/f64eval/gen_check.py {n} {seed}: closed-number evaluation (StrictTS.Proof.F64Eval) against the
host's binary64 arithmetic (Python floats; `%` is fmod). Each case is closed by `simp only [ts_sym]` (the
simprocs) and checked by the kernel. Run: `lake env lean tests/proof/F64EvalCheck.lean` (no output = all agree). -/
import StrictTS.Proof.F64Eval
open StrictTS
""")
for i in range(n):
    name, f = ops[i % len(ops)]
    a, b = rnd(r), rnd(r)
    try:
        res = f(a, b)
    except OverflowError:
        continue
    if not math.isnan(res) and res != 0 and abs(res) < 5e-324 / 2:
        continue
    print(f"example : {lit(a)} {name} {lit(b)} = {lit(res)} := by simp only [ts_sym]")
