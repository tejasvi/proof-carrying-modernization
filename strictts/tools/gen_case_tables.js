#!/usr/bin/env node
// Generates StrictTS/Str/CaseTables.lean: the Unicode default case mappings of
// String.prototype.toUpperCase / toLowerCase (full mappings, SpecialCasing's unconditional
// ones included) and the Cased / Case_Ignorable properties used by Final_Sigma, as Node's ICU
// computes them. Impl.host uses them for non-ASCII strings (the semantics leaves non-ASCII
// case mapping to `Impl`; theorems hold for every implementation).
//   node tools/gen_case_tables.js > StrictTS/Str/CaseTables.lean
'use strict';
const isSur = (c) => c >= 0xd800 && c <= 0xdfff;
const cps = (s) => [...s].map(ch => ch.codePointAt(0));
/** Runs of single-code-point mappings with one delta and a step of 1 or 2: (first, last, step, delta). */
function runs(f) {
  const singles = [], multi = [];
  for (let c = 0; c <= 0x10ffff; c++) {
    if (isSur(c)) continue;
    const s = String.fromCodePoint(c), m = cps(f(s));
    if (m.length === 1 && m[0] === c) continue;
    if (m.length === 1) singles.push([c, m[0] - c]); else multi.push([c, m]);
  }
  const out = [];
  let i = 0;
  while (i < singles.length) {
    const [c0, d0] = singles[i];
    let j = i, step = 0;
    if (i + 1 < singles.length && singles[i + 1][1] === d0 && (singles[i + 1][0] - c0 === 1 || singles[i + 1][0] - c0 === 2)) {
      step = singles[i + 1][0] - c0;
      while (j + 1 < singles.length && singles[j + 1][1] === d0 && singles[j + 1][0] - singles[j][0] === step) j++;
    }
    out.push([c0, singles[j][0], step || 1, d0]);
    i = j + 1;
  }
  return { out, multi };
}
function ranges(re) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const yes = c <= 0x10ffff && !isSur(c) && re.test(String.fromCodePoint(c));
    if (yes && start < 0) start = c;
    if (!yes && start >= 0) { out.push([start, c - 1]); start = -1; }
  }
  return out;
}
const up = runs(s => s.toUpperCase()), low = runs(s => s.toLowerCase());
const cased = ranges(/^\p{Cased}$/u), ign = ranges(/^\p{Case_Ignorable}$/u);
const runLit = (r) => r.map(([a, b, st, d]) => `(${a}, ${b}, ${st}, ${d < 0 ? `(${d})` : d})`).join(', ');
const multiLit = (m) => m.map(([c, xs]) => `(${c}, [${xs.join(', ')}])`).join(', ');
const rangeLit = (r) => r.map(([a, b]) => `(${a}, ${b})`).join(', ');
const lines = [];
lines.push(`/- Generated by tools/gen_case_tables.js from Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). Do not edit. -/`);
lines.push('namespace StrictTS.CaseTables');
lines.push('');
lines.push('/-- `toUpperCase` of one code point, single-code-point results: runs `(first, last, step, delta)`. -/');
lines.push(`def upperRuns : Array (Nat × Nat × Nat × Int) := #[${runLit(up.out)}]`);
lines.push('/-- `toUpperCase` of one code point with a result of several code points. -/');
lines.push(`def upperMulti : Array (Nat × List Nat) := #[${multiLit(up.multi)}]`);
lines.push('/-- `toLowerCase` of one code point (Final_Sigma aside), single-code-point results. -/');
lines.push(`def lowerRuns : Array (Nat × Nat × Nat × Int) := #[${runLit(low.out)}]`);
lines.push(`def lowerMulti : Array (Nat × List Nat) := #[${multiLit(low.multi)}]`);
lines.push('/-- The Unicode properties Cased and Case_Ignorable (ranges). -/');
lines.push(`def cased : Array (Nat × Nat) := #[${rangeLit(cased)}]`);
lines.push(`def caseIgnorable : Array (Nat × Nat) := #[${rangeLit(ign)}]`);
lines.push('');
lines.push('end StrictTS.CaseTables');
process.stdout.write(lines.join('\n') + '\n');
process.stderr.write(`upper runs ${up.out.length} multi ${up.multi.length}; lower runs ${low.out.length} multi ${low.multi.length}; cased ${cased.length}; ignorable ${ign.length}\n`);
