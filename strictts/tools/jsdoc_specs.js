#!/usr/bin/env node
// Specs written in TypeScript: turn JSDoc `@requires` / `@ensures` tags of top-level functions
// into Lean propositions about the translated program.
//
//   node tools/jsdoc_specs.js IN.ts OUTDIR NAMESPACE
//
// For each function `f(params): R` with tags, the spec expressions are added to a copy of the
// program as ordinary functions (so they are translated, checked and evaluated by the same
// semantics as the code they describe):
//   function f__requires(params): boolean { return (req1) && (req2) && ...; }
//   function f__ensures(result: R, params): boolean { return (ens1) && ...; }
// The copy is translated to OUTDIR/NAMESPACE.lean, and OUTDIR/NAMESPACESpecs.lean defines, for
// each such function, `f_spec : Prop`: from a world whose reference arguments are live and whose
// allocation pointer is fresh, if `f__requires` returns `true` (without changing the world), then
// every run of `f` that ends returns normally (no panic, no uncaught exception) with a value for
// which `f__ensures`, evaluated in the final world, returns `true`. Divergence is allowed
// (partial correctness). `@ensures` sees arrays and objects in their final state.
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const ts = require(path.join(ROOT, 'frontend', 'node_modules', 'typescript'));

const [inFile, outDir, ns] = process.argv.slice(2);
if (!inFile || !outDir || !ns) {
  console.error('usage: node tools/jsdoc_specs.js IN.ts OUTDIR NAMESPACE');
  process.exit(2);
}
const src = fs.readFileSync(inFile, 'utf8');
const sf = ts.createSourceFile(inFile, src, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);

function tagText(tag) {
  const c = tag.comment;
  if (typeof c === 'string') return c.trim();
  if (Array.isArray(c)) return c.map((p) => p.text).join('').trim();
  return '';
}

const specs = [];
for (const st of sf.statements) {
  if (!ts.isFunctionDeclaration(st) || !st.name || !st.body) continue;
  const tags = ts.getJSDocTags(st);
  const req = tags.filter((t) => t.tagName.text === 'requires').map(tagText).filter(Boolean);
  const ens = tags.filter((t) => t.tagName.text === 'ensures').map(tagText).filter(Boolean);
  if (req.length === 0 && ens.length === 0) continue;
  const name = st.name.text;
  const bad = st.parameters.find((p) => !ts.isIdentifier(p.name) || !p.type || p.initializer || p.dotDotDotToken);
  if (bad || !st.type || (st.typeParameters && st.typeParameters.length)) {
    console.error(`${inFile}: ${name}: skipped (parameters need plain names and types, and a return type)`);
    continue;
  }
  if (st.parameters.some((p) => p.name.text === 'result')) {
    console.error(`${inFile}: ${name}: skipped (a parameter is named \`result\`)`);
    continue;
  }
  const params = st.parameters.map((p) => p.getText(sf)).join(', ');
  const ret = st.type.getText(sf);
  const isAsync = (st.modifiers || []).some((m) => m.kind === ts.SyntaxKind.AsyncKeyword);
  if (isAsync) {
    console.error(`${inFile}: ${name}: skipped (async functions: not yet)`);
    continue;
  }
  specs.push({ name, params, ret, req, ens });
}

let extra = '\n// ---- specifications (generated from JSDoc by tools/jsdoc_specs.js) ----\n';
for (const s of specs) {
  const r = s.req.length ? s.req.map((e) => `(${e})`).join(' && ') : 'true';
  const e = s.ens.length ? s.ens.map((x) => `(${x})`).join(' && ') : 'true';
  extra += `function ${s.name}__requires(${s.params}): boolean {\n  return ${r};\n}\n`;
  const sep = s.params ? ', ' : '';
  extra += `function ${s.name}__ensures(result: ${s.ret}${sep}${s.params}): boolean {\n  return ${e};\n}\n`;
}

fs.mkdirSync(outDir, { recursive: true });
const augmented = path.join(outDir, path.basename(inFile, '.ts') + '.spec.ts');
fs.writeFileSync(augmented, src + extra);
const leanOut = path.join(outDir, ns + '.lean');
try {
  execFileSync('node', [path.join(ROOT, 'frontend', 'dist', 'cli.js'), '--namespace', ns, '-o', leanOut, augmented],
    { stdio: 'inherit' });
} catch (err) {
  console.error('translation failed (the spec expressions must be in the subset too)');
  process.exit(1);
}

const mod = path.relative(path.join(ROOT, 'examples'), leanOut).replace(/\.lean$/, '').split(path.sep).join('.');
let lean = `/- Generated by tools/jsdoc_specs.js from ${path.relative(ROOT, inFile)}. Do not edit. -/\n`;
lean += `import ${mod}\nimport StrictTS.Proof.Contract\n\nopen StrictTS JS\n\nnamespace ${ns}\n`;
for (const s of specs) {
  lean += `
/-- The JSDoc contract of \`${s.name}\`:
${s.req.map((e) => `\`@requires ${e}\``).join(', ') || 'no precondition'}; ${s.ens.map((e) => `\`@ensures ${e}\``).join(', ') || 'no postcondition'}. -/
def «${s.name}_spec» : Prop :=
  ∀ (I : Impl) (vs : Vals TT _) (w : World TT), Vals.Live w vs → JS.Fresh w →
    exec (callFun I program «${s.name}__requiresRef» vs) w = some (.ok (.bool true), w) →
    ∀ r w', exec (callFun I program «${s.name}Ref» vs) w = some (r, w') →
      ∃ v, r = .ok v ∧ exec (callFun I program «${s.name}__ensuresRef» (.cons v vs)) w' = some (.ok (.bool true), w')
`;
}
lean += `\nend ${ns}\n`;
const specsOut = path.join(outDir, ns + 'Specs.lean');
fs.writeFileSync(specsOut, lean);
console.log(`${specs.length} specification(s): ${specs.map((s) => s.name).join(', ')} -> ${path.relative(ROOT, specsOut)}`);
