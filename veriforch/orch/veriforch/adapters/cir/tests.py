# Text rewriting

def match_paren(s: str, i: int) -> int:
    """Index of the bracket closing s[i] (one of `([{`), skipping literals and comments."""
    pairs = {"(": ")", "[": "]", "{": "}"}
    stack = [pairs[s[i]]]
    j = i + 1
    while j < len(s):
        c = s[j]
        if c in "\"'":
            j = _skip_literal(s, j)
            continue
        if s.startswith("/*", j):
            k = s.find("*/", j + 2)
            j = len(s) if k < 0 else k + 2
            continue
        if s.startswith("//", j):
            k = s.find("\n", j)
            j = len(s) if k < 0 else k
            continue
        if c in pairs:
            stack.append(pairs[c])
        elif stack and c == stack[-1]:
            stack.pop()
            if not stack:
                return j
        j += 1
    raise ValueError("unbalanced brackets")


def _skip_literal(s: str, j: int) -> int:
    q = s[j]
    j += 1
    while j < len(s) and s[j] != q:
        j += 2 if s[j] == "\\" else 1
    return j + 1


def split_args(s: str) -> list[str]:
    """Top-level comma split of a call's argument text."""
    out, depth, cur, j = [], 0, [], 0
    while j < len(s):
        c = s[j]
        if c in "\"'":
            k = _skip_literal(s, j)
            cur.append(s[j:k])
            j = k
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        j += 1
    if "".join(cur).strip():
        out.append("".join(cur).strip())
    return out


_IDENT = re.compile(r"[A-Za-z_]\w*")


def rewrite_calls(text: str, handlers: dict, skip_decl: bool = False) -> str:
    """Replace calls `name(args)` for names in `handlers` with handler(args, call_start_in_output, out_so_far).
    Literals and comments are copied untouched."""
    out: list[str] = []
    j = 0
    while j < len(text):
        c = text[j]
        if c in "\"'":
            k = _skip_literal(text, j)
            out.append(text[j:k])
            j = k
            continue
        if text.startswith("/*", j) or text.startswith("//", j):
            end = text.find("*/", j + 2) + 2 if text.startswith("/*", j) else text.find("\n", j)
            end = len(text) if end < 2 or end <= j else end
            out.append(text[j:end])
            j = end
            continue
        m = _IDENT.match(text, j)
        if m and (j == 0 or not (text[j - 1].isalnum() or text[j - 1] in "_.>")):
            name = m.group(0)
            k = m.end()
            while k < len(text) and text[k] in " \t\n":
                k += 1
            if name in handlers and k < len(text) and text[k] == "(":
                close = match_paren(text, k)
                args = split_args(text[k + 1: close])
                rep = handlers[name](args, out)
                if rep is not None:
                    out.append(rep)
                    j = close + 1
                    continue
            out.append(name)
            j = m.end()
            continue
        out.append(c)
        j += 1
    return "".join(out)


def hoist_literals(body: str, prefix: str = "vo_s") -> tuple[str, list[str]]:
    """Replace string literals (adjacent ones merged) by local arrays declared at the top."""
    decls: list[str] = []
    out: list[str] = []
    j = 0
    while j < len(body):
        c = body[j]
        if c == "'":
            k = _skip_literal(body, j)
            out.append(body[j:k])
            j = k
            continue
        if body.startswith("/*", j) or body.startswith("//", j):
            end = body.find("*/", j + 2) + 2 if body.startswith("/*", j) else body.find("\n", j)
            end = len(body) if end < 2 or end <= j else end
            out.append(body[j:end])
            j = end
            continue
        if c == '"':
            lits = []
            k = j
            while k < len(body) and body[k] == '"':
                e = _skip_literal(body, k)
                lits.append(body[k:e])
                k2 = e
                while k2 < len(body) and body[k2] in " \t\n":
                    k2 += 1
                k = k2 if k2 < len(body) and body[k2] == '"' else e
            # leave array initialisers `x[] = "..."` alone
            before = "".join(out).rstrip()
            if before.endswith("=") and before[:-1].rstrip().endswith("]"):
                out.append(" ".join(lits))
            else:
                name = f"{prefix}{len(decls)}"
                decls.append(f"char {name}[] = {' '.join(lits)};")
                out.append(name)
            j = k
            continue
        out.append(c)
        j += 1
    return "".join(out), decls


