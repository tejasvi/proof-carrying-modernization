"""C test promotion for cirlean.

Pipeline: clang AST JSON of the test files -> test cases -> harness C code (concrete and symbolic) ->
native run under UBSan -> translation with the target through ClangIR + cir2lean -> theorem statements
(`Returns ctx fn_h.sym args m (fun _ _ => True)`) -> elaboration check in Lean.

The test code is rewritten into the subset cirlean models, without special cases for any project:
* helpers taking `...` or `va_list` get an explicit argument array (`vo_va_item`) and a cursor (`vo_va`);
* `malloc(n * sizeof(T))` in a helper becomes a caller-provided buffer parameter of `n` elements of T;
* `free`, `printf`-family calls disappear; `strlen`/`strncmp`/`strcmp`/`memcmp` become small C shims;
* whole-array `memset(a, 0, sizeof a)` / `memcpy(d, s, sizeof s)` become element loops;
* string literals in harness bodies become local arrays (no globals, so theorems quantify over memory);
* check macros become `VO_ASSERT`, which is `assert` for the bridge (a failed assert is UB in cirlean)
  and an early `return __LINE__` natively.
"""
