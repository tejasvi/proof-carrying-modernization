@dataclass
class Ctx:
    target: Target
    variant: Variant
    fns: dict[str, Fn]
    api: set[str]
    tside: dict[str, Fn]
    calls_api: dict[str, bool]
    typedefs: dict[str, str]
    files: dict[str, str] = field(default_factory=dict)

    def text(self, fn: Fn) -> str:
        if fn.file not in self.files:
            self.files[fn.file] = Path(fn.file).read_bytes().decode("utf-8", "replace")
        return self.files[fn.file]


def build_ctx(target: Target, variant: Variant, work: Path) -> Ctx:
    fns: dict[str, Fn] = {}
    tdefs: dict[str, str] = {}
    test_paths = [Path(target.root) / t for t in target.tests]
    for tf in test_paths:
        ast = clang_ast(target, variant, tf.resolve(), work)
        fns.update(index_functions(ast))
        tdefs.update(typedef_records(ast))
    test_dirs = {p.resolve().parent for p in test_paths}
    tside = {n: f for n, f in fns.items() if Path(f.file).resolve().parent in test_dirs}
    api = set(target.entry) or {n for n, f in fns.items() if n not in tside and not f.static}
    calls = {n: {callee_name(c) for c in walk(f.body) if c.get("kind") == "CallExpr"} for n, f in tside.items()}
    capi = {n: bool(calls[n] & api) for n in tside}
    changed = True
    while changed:
        changed = False
        for n in tside:
            if not capi[n] and any(capi.get(c, False) for c in calls[n] if c in tside):
                capi[n] = changed = True
    return Ctx(target, variant, fns, api, tside, capi, tdefs)


def test_functions(cx: Ctx) -> list[str]:
    main = cx.tside.get("main")
    names: list[str] = []
    if main:
        for d in walk(main.body):
            if d.get("kind") == "DeclRefExpr":
                n = d.get("referencedDecl", {}).get("name")
                if n in cx.tside and n != "main" and not cx.tside[n].params and n not in names:
                    names.append(n)
    if not names:
        names = [n for n in cx.tside if n.lower().startswith("test") and not cx.tside[n].params]
    return names


def _line(text: str, off: int) -> int:
    return text.count("\n", 0, off) + 1


def _check_stmt_span(text: str, stmt: dict) -> tuple[int, int, str] | None:
    """For a statement produced by a check macro: (start, end, macro) in the test file."""
    b = exp_begin(stmt)
    if b is None:
        return None
    m = _IDENT.match(text, b)
    if not m or m.group(0) not in CHECK_MACROS:
        return None
    k = m.end()
    while text[k] in " \t":
        k += 1
    if text[k] != "(":
        return None
    close = match_paren(text, k)
    end = close + 1
    while end < len(text) and text[end] in " \t":
        end += 1
    if end < len(text) and text[end] == ";":
        end += 1
    return b, end, m.group(0)


def _check_cond(stmt: dict) -> dict | None:
    """The condition argument of a `do { if (!(cond)) ... } while (0)` / `if (!(cond))` / assert expansion."""
    for d in walk(stmt):
        if d.get("kind") == "IfStmt":
            c = strip(d["inner"][0])
            if c.get("kind") == "UnaryOperator" and c.get("opcode") == "!":
                return strip(c["inner"][0])
            return c
        if d.get("kind") == "ConditionalOperator":
            return strip(d["inner"][0])
    return None


def _string_assignments(fn: Fn) -> list[tuple[int, str, dict]]:
    """(offset, variable, StringLiteral node) for `v = "..."` and `T *v = "..."` in a function."""
    out = []
    for d in walk(fn.body):
        if d.get("kind") == "BinaryOperator" and d.get("opcode") == "=":
            lhs, rhs = strip(d["inner"][0]), strip(d["inner"][1])
            if lhs.get("kind") == "DeclRefExpr" and rhs.get("kind") == "StringLiteral":
                out.append((span(d)[0] or 0, lhs["referencedDecl"]["name"], rhs))
        if d.get("kind") == "VarDecl" and d.get("inner"):
            init = strip(d["inner"][0])
            if init.get("kind") == "StringLiteral" and "*" in d.get("type", {}).get("qualType", ""):
                out.append((span(d)[0] or 0, d["name"], init))
    return sorted(out, key=lambda t: t[0])


def _arg(cx: Ctx, fn: Fn, node: dict, at: int, ctype: str) -> Arg:
    n = strip(node)
    k = n.get("kind")
    text = cx.text(fn)
    b, e = span(node)
    src = text[b:e] if b is not None else ""
    if k == "StringLiteral":
        return Arg(n.get("value", src), "string", n.get("value"), ctype)
    if k == "IntegerLiteral":
        return Arg(src or n["value"], "int", int(n["value"]), ctype)
    if k == "UnaryOperator" and n.get("opcode") == "-" and strip(n["inner"][0]).get("kind") == "IntegerLiteral":
        return Arg(src, "int", -int(strip(n["inner"][0])["value"]), ctype)
    if k == "DeclRefExpr":
        rd = n.get("referencedDecl", {})
        if rd.get("kind") == "EnumConstantDecl":
            return Arg(rd["name"], "enum", rd["name"], ctype)
        if rd.get("kind") in ("VarDecl", "ParmVarDecl"):
            last = [s for s in _string_assignments(fn) if s[1] == rd["name"] and s[0] < at]
            if last:
                lit = last[-1][2]
                return Arg(lit.get("value", ""), "string", lit.get("value"), ctype)
    return Arg(src, "expr", None, ctype)


def extract(target: Target, variant: Variant, work: Path) -> tuple[list[TestCase], Ctx]:
    cx = build_ctx(target, variant, work)
    cases: list[TestCase] = []
    for tname in test_functions(cx):
        fn = cx.tside[tname]
        text = cx.text(fn)
        callees = [(c, callee_name(c)) for c in walk(fn.body) if c.get("kind") == "CallExpr"]
        if not any(n in cx.api or cx.calls_api.get(n) for _, n in callees):
            continue        # nothing reaches the API in this variant
        direct = any(n in cx.api for _, n in callees)
        per_call: list[tuple[dict, dict, tuple[int, int, str]]] = []
        if not direct:
            ok = True
            for stmt in fn.body.get("inner", []):
                wcalls = [c for c in walk(stmt) if c.get("kind") == "CallExpr"
                          and callee_name(c) in cx.tside and cx.calls_api.get(callee_name(c))]
                if not wcalls:
                    continue
                sp = _check_stmt_span(text, stmt)
                if sp is None or len(wcalls) != 1:
                    ok = False
                    break
                per_call.append((stmt, wcalls[0], sp))
            if not ok:
                per_call = []
        if per_call:
            for k, (stmt, call, sp) in enumerate(per_call, start=1):
                wname = callee_name(call)
                wfn = cx.tside[wname]
                at = sp[0]
                args = []
                for i, a in enumerate(call["inner"][1:]):
                    ctype = wfn.params[i][1] if i < len(wfn.params) else strip(a).get("type", {}).get("qualType", "")
                    args.append(_arg(cx, fn, a, at, ctype))
                roles = classify_params(cx, wfn)
                cases.append(TestCase(
                    name=f"{tname}#{k}", origin=f"{fn.file}:{_line(text, sp[0])}", function=tname,
                    kind="wrapper_call", wrapper=wname, args=args, stmt=text[sp[0]:sp[1]],
                    inputs=[wfn.params[i][0] for i in range(len(wfn.params)) if roles.get(wfn.params[i][0]) == "input"],
                    expected=[wfn.params[i][0] for i in range(len(wfn.params)) if roles.get(wfn.params[i][0]) == "expect"]
                    + (["..."] if wfn.variadic else [])))
        else:
            cases.append(TestCase(name=tname, origin=f"{fn.file}:{_line(text, fn.begin)}", function=tname,
                                  kind="whole_function", stmt=text[fn.begin:fn.end]))
    return cases, cx


