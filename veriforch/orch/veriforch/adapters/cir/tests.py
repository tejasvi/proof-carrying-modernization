# AST access

def clang_ast(target: Target, variant: Variant, test_file: Path, work: Path) -> dict:
    flags = [f"-I{Path(target.root) / i}" for i in target.include] + [f"-I{Path(target.root)}"] + variant.flags \
        + target.extra.get("cflags", [])
    key = sha256(test_file.read_bytes() + json.dumps(flags).encode() + _deps_bytes(test_file))[:16]
    out = work / f"ast_{test_file.stem}_{key}.json"
    if not out.exists():
        cmd = [str(RUN1), "-t", "300", "-c", "0.05", "--", str(cbuild.CLANG), "-Xclang", "-ast-dump=json",
               "-fsyntax-only", *flags, str(test_file)]
        with open(out.with_suffix(".tmp"), "w") as f:
            p = subprocess.run(cmd, stdout=f, stderr=subprocess.PIPE, text=True, timeout=400,
                               env=dict(os.environ, VO_ROOT=str(VO_ROOT)))
        if p.returncode != 0:
            raise RuntimeError(f"clang AST dump failed: {p.stderr[-2000:]}")
        out.with_suffix(".tmp").replace(out)
    return json.loads(out.read_text())


def _deps_bytes(test_file: Path) -> bytes:
    b = b""
    for h in sorted(test_file.parent.glob("*.h")):
        b += h.read_bytes()
    return b


def walk(n: dict):
    yield n
    for c in n.get("inner", []) or []:
        if isinstance(c, dict):
            yield from walk(c)


def strip(n: dict) -> dict:
    while n.get("kind") in ("ImplicitCastExpr", "ParenExpr", "CStyleCastExpr") and n.get("inner"):
        n = n["inner"][0]
    return n


def callee_name(call: dict) -> str | None:
    if not call.get("inner"):
        return None
    for d in walk(call["inner"][0]):
        if d.get("kind") == "DeclRefExpr":
            return d.get("referencedDecl", {}).get("name")
    return None


def refs(n: dict) -> set[str]:
    return {d["referencedDecl"]["name"] for d in walk(n)
            if d.get("kind") == "DeclRefExpr" and d.get("referencedDecl", {}).get("name")}


def _loc(x: dict, prefer: str = "spellingLoc") -> dict:
    return x.get(prefer) or x.get("spellingLoc") or x


def span(n: dict) -> tuple[int | None, int | None]:
    """Byte span of a node in the file where it is spelled (macro arguments: the invoking file)."""
    r = n.get("range", {})
    b, e = _loc(r.get("begin", {})), _loc(r.get("end", {}))
    if b.get("offset") is None or e.get("offset") is None:
        return None, None
    return b["offset"], e["offset"] + e.get("tokLen", 0)


def exp_begin(n: dict) -> int | None:
    b = n.get("range", {}).get("begin", {})
    return _loc(b, "expansionLoc").get("offset")


@dataclass
class Fn:
    name: str
    file: str
    begin: int
    end: int
    params: list[tuple[str, str]]
    variadic: bool
    static: bool
    node: dict
    body: dict


def index_functions(ast: dict) -> dict[str, Fn]:
    """Function definitions with the file each is spelled in (clang prints `file` only when it changes)."""
    cur: str | None = None
    out: dict[str, Fn] = {}
    for n in ast.get("inner", []):
        for key in ("loc", "range"):
            v = n.get(key, {})
            subs = [v] if key == "loc" else [v.get("begin", {}), v.get("end", {})]
            for s in subs:
                for s2 in (s, s.get("spellingLoc", {}), s.get("expansionLoc", {})):
                    if isinstance(s2, dict) and "file" in s2:
                        cur = s2["file"]
                        break
                break
            if key == "loc":
                pass
        if n.get("kind") != "FunctionDecl":
            continue
        body = next((c for c in n.get("inner", []) if c.get("kind") == "CompoundStmt"), None)
        if body is None or cur is None:
            continue
        b, e = span(n)
        params = [(c.get("name", ""), c.get("type", {}).get("qualType", "")) for c in n.get("inner", [])
                  if c.get("kind") == "ParmVarDecl"]
        qt = n.get("type", {}).get("qualType", "")
        out[n["name"]] = Fn(n["name"], cur, b, e, params, qt.rstrip().endswith("...)"),
                            n.get("storageClass") == "static", n, body)
    return out


def typedef_records(ast: dict) -> dict[str, str]:
    """typedef name -> record name (`jsmntok_t` -> `jsmntok`)."""
    out = {}
    for n in ast.get("inner", []):
        if n.get("kind") == "TypedefDecl":
            qt = n.get("type", {}).get("qualType", "")
            m = re.match(r"(?:struct|union)\s+(\w+)$", qt.strip())
            if m:
                out[n["name"]] = m.group(1)
    return out


