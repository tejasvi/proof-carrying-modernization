def prune_spec(target: Target) -> dict:
    """The target's prune file: {"opaque": [{pattern, reason, ...}], "dyn_fields": "opaque", "pruned": [{kind, path,
    file, line, end, reason, message, iteration}]} (empty when the target has none)."""
    if not target.extra.get("aeneas_prune_file"):
        return {}
    p = _opt_path(target, "aeneas_prune_file")
    return json.loads(p.read_text()) if p.exists() else {}


_PRUNE_KINDS = {"trait_decl": "trait_decls", "trait_impl": "trait_impls", "fun_decl": "fun_decls"}


def _llbc_files(t: dict) -> list[str]:
    out = []
    for f in t["files"]:
        nm = f.get("name") if isinstance(f, dict) else f
        out.append(next(iter(nm.values())) if isinstance(nm, dict) else str(nm))
    return out


def llbc_items(t: dict) -> list[dict]:
    """The crate's own trait declarations, trait impls and functions, and every library trait declaration (Aeneas
    also aborts on a library trait): kind, id, path, span."""
    files = _llbc_files(t)
    out = []
    for kind, key in _PRUNE_KINDS.items():
        for x in t.get(key) or []:
            if not x or not (x["item_meta"].get("is_local") or kind == "trait_decl"):
                continue
            sp = _span(x["item_meta"].get("span"))
            if sp:
                out.append({"kind": kind, "id": x["def_id"], "path": _name(x["item_meta"]["name"]),
                            "file": files[sp["file_id"]], "l0": sp["beg"]["line"], "c0": sp["beg"]["col"],
                            "l1": sp["end"]["line"], "c1": sp["end"]["col"]})
    return out


def _ty_name(t: dict, ty) -> str:
    """A type as named in `impl_of`: an ADT by its path, anything else by its JSON."""
    ty = ty.get("Untagged", ty) if isinstance(ty, dict) else ty
    if isinstance(ty, dict) and "Adt" in ty and isinstance(ty["Adt"].get("id"), int):
        d = t["type_decls"][ty["Adt"]["id"]] if ty["Adt"]["id"] < len(t["type_decls"]) else None
        if d:
            return _name(d["item_meta"]["name"])
    return json.dumps(ty, sort_keys=True)


def _impl_identity(t: dict, x: dict) -> list[str]:
    """[trait path, Self type, the trait's type arguments...] of a trait impl."""
    tr = x.get("impl_trait") or {}
    d = t["trait_decls"][tr["id"]] if isinstance(tr.get("id"), int) and tr["id"] < len(t["trait_decls"]) else None
    return ([_name(d["item_meta"]["name"]) if d else str(tr.get("id"))]
            + [_ty_name(t, ty) for ty in (tr.get("generics") or {}).get("types", [])])


def _resolve(t: dict, pruned: list[dict], skipped: list | None = None) -> list[tuple[str, int, dict]]:
    """The pruned items in this LLBC, by kind, path and span (ids differ between Charon runs), or a trait impl by
    `impl_of` (its identity). An entry that does not match exactly one item is an error, unless `skipped` is given
    (the prune file's `"missing": "skip"`, for revisions other than the one it was made for): it is listed there."""
    its = llbc_items(t)
    out = []
    for e in pruned:
        if e.get("impl_of"):
            hit = [{"id": x["def_id"]} for x in t["trait_impls"] if x and x["item_meta"].get("is_local")
                   and e["kind"] == "trait_impl" and _impl_identity(t, x) == list(e["impl_of"])]
        else:
            hit = [x for x in its if x["kind"] == e["kind"] and x["path"] == e["path"] and x["file"] == e["file"]
                   and x["l0"] == e["line"] and x["l1"] == e["end"]]
        if len(hit) != 1:
            what = f"{e['kind']} {e.get('impl_of') or e.get('path')} {e.get('file', '')}:{e.get('line', '')}"
            if skipped is None:
                raise RuntimeError(f"pruned item {what} matches {len(hit)} items")
            skipped.append(f"{what}: {len(hit)} matches")
            continue
        out.append((e["kind"], hit[0]["id"], e))
    return out


def opaque_dyn_fields(t: dict) -> list[str]:
    """Give every field whose type contains a `dyn Trait` the opaque type vo_dyn::DynValue (a new opaque type
    declaration). Returns the changed fields (type path.field)."""
    proto = next(x for x in t["type_decls"] if x and x.get("kind") == "Opaque" and x.get("src") == "Normal"
                 and not x["generics"]["types"] and not x["generics"]["regions"])
    nid = len(t["type_decls"])
    meta = json.loads(json.dumps(proto["item_meta"]))
    meta.update({"name": [{"Ident": ["vo_dyn", 0]}, {"Ident": ["DynValue", 0]}], "source_text": None,
                 "is_local": False})
    meta["attr_info"] = {**meta.get("attr_info", {}), "attributes": []}
    t["type_decls"].append({"def_id": nid, "item_meta": meta, "generics": json.loads(json.dumps(proto["generics"])),
                            "src": "Normal", "kind": "Opaque", "layout": [], "ptr_metadata": "None",
                            "marker_traits": None})
    t["item_names"].append({"key": {"Type": nid}, "value": meta["name"]})
    t["ordered_decls"].insert(0, {"Type": {"NonRec": nid}})
    changed = []
    for x in t["type_decls"]:
        if not x or x["def_id"] == nid or not isinstance(x.get("kind"), dict):
            continue
        k = x["kind"]
        groups = [k["Struct"]] if "Struct" in k else [v["fields"] for v in k["Enum"]] if "Enum" in k else []
        for fields in groups:
            for f in fields:
                if '"DynTrait"' in json.dumps(f["ty"]):
                    f["ty"] = {"Untagged": {"Adt": {"id": nid, "generics": {"regions": [], "types": [],
                                                                            "const_generics": [], "trait_refs": []},
                                                    "builtin": None}}}
                    changed.append(f"{_name(x['item_meta']['name'])}.{f.get('name')}")
    return changed


def split_mixed_groups(t: dict) -> list[list[str]]:
    """Aeneas stops analysing functions at the first mixed declaration group (FunsAnalysis.analyze_decl_groups:
    `MixedGroup ids :: _` drops the rest), so every function ordered after it fails ("Internal error" when its
    signature is translated). The mixed groups of a crate with dyn traits are the cycles a vtable makes (vtable type
    <-> trait declaration, trait impl <-> vtable global). With the dyn fields opaque (opaque_dyn_fields) and the
    vtable references of trait declarations and impls dropped (`None`, "Lazy": as for a trait never used as dyn),
    each member becomes a group of its own: types, trait declarations, functions, impls, globals. Returns the split
    groups (item names)."""
    key = {"Type": "type_decls", "Fun": "fun_decls", "Global": "global_decls", "TraitDecl": "trait_decls",
           "TraitImpl": "trait_impls"}
    order = {"Type": 0, "TraitDecl": 1, "Fun": 2, "TraitImpl": 3, "Global": 4}
    for x in t["trait_decls"]:
        if x and x.get("vtable") is not None:
            x["vtable"] = None
    for x in t["trait_impls"]:
        if x and isinstance(x.get("vtable"), dict):
            x["vtable"] = "Lazy"
    groups, split = [], []
    for g in t["ordered_decls"]:
        k = next(iter(g))
        if k != "Mixed":
            groups.append(g)
            continue
        members = sorted(g[k]["Rec"], key=lambda e: order[next(iter(e))])
        funs = [e["Fun"] for e in members if "Fun" in e]
        for e in members:
            ek = next(iter(e))
            if ek == "Fun":
                if funs:
                    groups.append({"Fun": {"Rec": funs}} if len(funs) > 1 else {"Fun": {"NonRec": funs[0]}})
                    funs = []
            else:
                groups.append({ek: {"NonRec": e[ek]}})
        split.append([f"{next(iter(e))}:{_name(t[key[next(iter(e))]][e[next(iter(e))]]['item_meta']['name'])}"
                      for e in members if t[key[next(iter(e))]][e[next(iter(e))]]])
    t["ordered_decls"] = groups
    return split


def prune_dyn_trait_methods(t: dict) -> dict[int, str]:
    """Drop every trait method whose signature has a dyn type (Aeneas aborts on some, e.g. a `Box<dyn ..>` output,
    and Lean rejects the trait structure of the others: no universe level for the `Dyn` field). The method's entry
    becomes empty (`None`, as for a method Charon did not translate: the other methods keep their indices) and every
    impl drops the method implementing it. Returns the removed functions (impl methods, default bodies): id -> reason."""
    removed: dict[int, str] = {}
    for x in t["trait_decls"]:
        if not x:
            continue
        reason = f"dyn-trait-signature:{_name(x['item_meta']['name'])}"
        idx = set()
        for i, m in enumerate(x.get("methods") or []):
            if m and '"DynTrait"' in json.dumps(m["skip_binder"].get("signature")):
                idx.add(i)
                dflt = m["skip_binder"].get("default")
                if isinstance(dflt, dict) and isinstance(dflt.get("id"), int):
                    removed[dflt["id"]] = reason
                x["methods"][i] = None
        if not idx:
            continue
        for y in t["trait_impls"]:
            if not y or (y.get("impl_trait") or {}).get("id") != x["def_id"]:
                continue
            keep = []
            for m in y.get("methods") or []:
                k = (m or {}).get("kind", {}).get("TraitMethod") if isinstance((m or {}).get("kind"), dict) else None
                if m and k and k[0] == x["def_id"] and k[1] in idx:
                    if isinstance(m["skip_binder"].get("id"), int):
                        removed[m["skip_binder"]["id"]] = reason
                else:
                    keep.append(m)
            y["methods"] = keep
    return removed


def prune_llbc(d: dict, spec: dict) -> dict[int, str]:
    """Apply the prune file to an LLBC (in place, before Aeneas). Returns the removed functions: id -> reason
    (`<reason>` of `gap:aeneas-abort:<reason>`). A removed function leaves no reference behind in impl method lists
    or trait default bodies; its callers keep their calls (Aeneas reports them per function)."""
    t = d["translated"]
    if spec.get("dyn_fields") == "opaque":
        spec["_changed_fields"] = opaque_dyn_fields(t)
    if spec.get("mixed_groups") == "split":
        spec["_split_groups"] = split_mixed_groups(t)
    # names only: Aeneas names an impl after its trait and type, so `From<io::Error>` and `From<uuid::Error>` for one
    # type are both `...Insts.CoreConvertFromError` ("Name clash detected"; the later one silently replaces the other);
    # the rename is what `#[charon::rename("..")]` on the item would give
    skipped: list | None = [] if spec.get("missing") == "skip" else None
    for kind, i, e in _resolve(t, spec.get("rename", []), skipped):
        x = t[_PRUNE_KINDS[kind]][i]
        x["item_meta"].setdefault("attr_info", {})["rename"] = e["rename"]
    removed: dict[int, str] = prune_dyn_trait_methods(t) if spec.get("dyn_trait_methods") == "prune" else {}
    traits: dict[int, str] = {}
    impls: dict[int, str] = {}
    for kind, i, e in _resolve(t, spec.get("pruned", []), skipped):
        reason = e.get("reason") or e["path"]
        if kind == "trait_decl":
            traits[i] = reason
        elif kind == "trait_impl":
            impls[i] = reason
        else:
            removed[i] = reason
    for i, reason in traits.items():
        tr = t["trait_decls"][i]
        for m in tr.get("methods") or []:
            dflt = m["skip_binder"].get("default") if m else None
            if isinstance(dflt, dict) and isinstance(dflt.get("id"), int):
                removed[dflt["id"]] = reason
        tr["methods"] = []
    for x in t["trait_impls"]:
        if not x:
            continue
        reason = impls.get(x["def_id"]) or traits.get((x.get("impl_trait") or {}).get("id"))
        if reason:
            for m in x.get("methods") or []:
                if m and isinstance(m["skip_binder"].get("id"), int):
                    removed[m["skip_binder"]["id"]] = reason
            x["methods"] = []
    for x in t["trait_impls"]:
        if x and x.get("methods"):
            x["methods"] = [m for m in x["methods"] if not (m and m["skip_binder"].get("id") in removed)]
    for x in t["trait_decls"]:
        for m in (x or {}).get("methods") or []:
            dflt = m["skip_binder"].get("default") if m else None
            if isinstance(dflt, dict) and dflt.get("id") in removed:
                m["skip_binder"]["default"] = None
    for i in removed:
        t["fun_decls"][i] = None
    groups = []
    for g in t["ordered_decls"]:
        k = next(iter(g))
        v = g[k]
        rk = next(iter(v))
        if k == "Fun" and rk == "NonRec":
            if v[rk] in removed:
                continue
        elif k == "Fun" and rk == "Rec":
            v = {rk: [i for i in v[rk] if i not in removed]}
            if not v[rk]:
                continue
        elif k == "Mixed":
            v = {rk: [e for e in v[rk] if not ("Fun" in e and e["Fun"] in removed)]}
            if not v[rk]:
                continue
        groups.append({k: v})
    t["ordered_decls"] = groups
    if skipped:
        spec["_skipped_entries"] = skipped
    return removed


# -- the LLBC: functions, spans, calls -------------------------------------------------------------------------------

def _name(n: list) -> str:
    out = []
    for c in n:
        if "Ident" in c:
            out.append(c["Ident"][0])
        elif "Impl" in c:
            out.append("{impl}")
        else:
            out.append("{" + next(iter(c)) + "}")
    return "::".join(out)


def _span(d) -> dict | None:
    if isinstance(d, dict):
        if "Untagged" in d:
            return d["Untagged"]["data"]
        if "data" in d:
            return d["data"]
    return None


def _fun_ids(body) -> set[int]:
    """def ids of the functions a body calls or takes a pointer to (every `{"Fun": id}` below it)."""
    out: set[int] = set()
    stack = [body]
    while stack:
        x = stack.pop()
        if isinstance(x, dict):
            for k, v in x.items():
                if k == "Fun" and isinstance(v, int):
                    out.add(v)
                else:
                    stack.append(v)
        elif isinstance(x, list):
            stack.extend(x)
    return out


def llbc_functions(llbc: Path) -> tuple[list[dict], dict]:
    """The crate's own functions: path, span (file, lines), doc attributes, visibility, errors, local callees (by def
    id) and library callees (by path)."""
    d = json.loads(llbc.read_text())
    t = d["translated"]
    files = []
    for f in t["files"]:
        nm = f.get("name") if isinstance(f, dict) else f
        files.append(next(iter(nm.values())) if isinstance(nm, dict) else str(nm))
    decls = {f["def_id"]: f for f in t["fun_decls"] if f}
    # the initialisers of constants and statics are functions too: they belong to their global, not units
    inits = set()
    for g in t.get("global_decls") or []:
        if g:
            inits |= _fun_ids(g.get("value") or g.get("init") or {})
    out = []
    for fid, f in decls.items():
        im = f["item_meta"]
        if not im.get("is_local"):
            continue
        path = _name(im["name"])
        sp = _span(im.get("span"))
        attrs = [a.get("DocComment", "").strip() for a in (im.get("attr_info") or {}).get("attributes", [])
                 if isinstance(a, dict) and "DocComment" in a]
        body = f.get("body")
        callees = sorted(i for i in _fun_ids(body) if i != fid) if isinstance(body, dict) else []
        out.append({"id": fid, "path": path, "global": fid in inits, "file": files[sp["file_id"]] if sp else "",
                    "line": sp["beg"]["line"] if sp else 0, "col": sp["beg"]["col"] if sp else 0,
                    "end": sp["end"]["line"] if sp else 0, "end_col": sp["end"]["col"] if sp else 0,
                    "public": bool((im.get("attr_info") or {}).get("public")), "attrs": attrs,
                    "has_errors": bool(im.get("has_errors")), "opacity": im.get("opacity"),
                    "has_body": isinstance(body, dict), "local_callees": [i for i in callees if i in decls and
                                                                          decls[i]["item_meta"].get("is_local")],
                    "lib_callees": sorted({_name(decls[i]["item_meta"]["name"]) for i in callees if i in decls
                                           and not decls[i]["item_meta"].get("is_local")})})
    return out, {"charon_version": d.get("charon_version"), "has_errors": d.get("has_errors"),
                 "crate_name": t.get("crate_name")}


# -- the Lean side: definitions, split modules ------------------------------------------------------------------------

_DEF_RE = re.compile(r"^(?:@\[[^\n]*\]\s*)?(?:private |protected |noncomputable |unsafe |partial |nonrec )*"
                     r"(?:def|abbrev|theorem|instance|opaque|axiom|structure|inductive|class)[ \t]*\n?[ \t]+"
                     r"(?P<name>[^\s:({\[]+)",
                     re.M)
_SORRY_RE = re.compile(r"(?<![\w.'])sorry(?![\w.'])")
_SRC_RE = re.compile(r"Source: '(?P<file>[^']+)', lines (?P<l0>\d+):(?P<c0>\d+)-(?P<l1>\d+):(?P<c1>\d+)")
_TOKEN_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_'!?]*(?:\.(?:[A-Za-z_][A-Za-z0-9_'!?]*|«[^»]*»))*")


def _docs(text: str):
    """Aeneas's doc comments `/-- [<rust path>]<kind>: ... Source: '<file>', lines l0:c0-l1:c1 ... -/`:
    (start, end, path, kind, span) for each (the path may contain brackets, e.g. `[u8]` in a trait impl)."""
    for m in re.finditer(r"/--(.*?)-/\n?", text, re.S):
        inner = m.group(1).lstrip()
        if not inner.startswith("["):
            continue
        depth, i = 0, 0
        for i, ch in enumerate(inner):
            if ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
                if depth == 0:
                    break
        path = inner[1:i]
        kind = inner[i + 1:].split("\n", 1)[0].strip().strip(":").strip()
        s = _SRC_RE.search(inner)
        span = (s.group("file"), int(s.group("l0")), int(s.group("c0")), int(s.group("l1")), int(s.group("c1"))) \
            if s else None
        yield m.start(), m.end(), path, kind, span


def split_lean(text: str) -> tuple[list[str], str, list[dict], str]:
    """A generated file -> (header lines, namespace, chunks, trailer). A chunk is one definition with its doc comment,
    or one `mutual ... end` block: {"text", "paths": [(path, kind, span)], "defs": [names]}."""
    lines = text.splitlines(keepends=True)
    try:
        ns_i = next(i for i, l in enumerate(lines) if l.startswith("namespace "))
    except StopIteration:
        return lines, "", [], ""
    ns = lines[ns_i].split()[1]
    try:
        end_i = max(i for i, l in enumerate(lines) if l.strip() == f"end {ns}")
    except ValueError:
        end_i = len(lines)
    header, body, trailer = lines[:ns_i], lines[ns_i + 1:end_i], "".join(lines[end_i + 1:])
    chunks: list[list[str]] = []
    cur: list[str] = []
    in_mutual = in_doc = False
    for l in body:
        starts = (l.startswith("/--") or l.startswith("mutual")) and not in_mutual and not in_doc
        if starts and any(x.strip() for x in cur):
            chunks.append(cur)
            cur = []
        if l.startswith("mutual") and not in_doc:
            in_mutual = True
        elif in_mutual and l.rstrip() == "end":
            in_mutual = False
        if l.startswith("/--") and "-/" not in l:
            in_doc = True
        elif in_doc and "-/" in l:
            in_doc = False
        cur.append(l)
    if any(x.strip() for x in cur):
        chunks.append(cur)
    out = []
    for c in chunks:
        t = "".join(c)
        out.append({"text": t, "paths": [(p, k, sp) for _, _, p, k, sp in _docs(t)], "defs": _DEF_RE.findall(t)})
    return header, ns, out, trailer


def normalize_chunk(text: str) -> str:
    """A chunk without the positions in its doc comments (`Source: ..., lines ...`): a function that only moved has the
    same module text, so its compiled module and proof are reused and CI does not count it as changed."""
    out, last = [], 0
    for s, e, path, kind, _ in _docs(text):
        out.append(text[last:s] + f"/-- [{path}]" + (f": {kind}" if kind else "") + " -/\n")
        last = e
    return "".join(out) + text[last:]


def _tokens(text: str) -> set[str]:
    return set(_TOKEN_RE.findall(re.sub(r"/--.*?-/", "", text, flags=re.S)))


def _sccs(nodes: list[str], edges: dict[str, set[str]]) -> list[list[str]]:
    """Strongly connected components, callees before callers (Tarjan, iterative)."""
    index, low, on, stack, out = {}, {}, set(), [], []
    counter = [0]
    for root in nodes:
        if root in index:
            continue
        work = [(root, iter(sorted(edges.get(root, ()))))]
        index[root] = low[root] = counter[0]
        counter[0] += 1
        stack.append(root)
        on.add(root)
        while work:
            v, it = work[-1]
            w = next(it, None)
            if w is not None:
                if w not in index:
                    index[w] = low[w] = counter[0]
                    counter[0] += 1
                    stack.append(w)
                    on.add(w)
                    work.append((w, iter(sorted(edges.get(w, ())))))
                elif w in on:
                    low[v] = min(low[v], index[w])
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[v])
            if low[v] == index[v]:
                comp = []
                while True:
                    w = stack.pop()
                    on.discard(w)
                    comp.append(w)
                    if w == v:
                        break
                out.append(sorted(comp))
    return out


def _component(s: str, limit: int = 120) -> str:
    """A module-name component (file names are limited to 255 bytes)."""
    s = _ident(s)
    return s if len(s) <= limit else s[: limit - 17] + "_" + sha256(s)[:16]


def _header(lines: list[str], imports: list[str]) -> str:
    """The generated header with its imports replaced (`module`, the options and `open`s are kept)."""
    out, done = [], False
    for l in lines:
        if re.match(r"^(?:public )?import ", l):
            if not done:
                out += [f"public import {i}\n" for i in imports]
                done = True
            continue
        out.append(l)
    return "".join(out)


SUPPORT_MODULE = "VerifOrch.Rust.Support"
SUPPORT_LEAN = VO_ROOT / "VerifOrch" / "Rust" / "Support.lean"


def split_modules(gdir: Path, prefix: str, crate_ns: str | None = None) -> dict:
    """Aeneas's Types.lean / Funs.lean (with the external templates) -> modules below `prefix`:
    {"modules": {name: text}, "order": [...], "deps": {name: [imported generated modules]}, "nodes": [...],
     "externals": [...], "ns": crate namespace}. Nodes are the definition groups of one Rust item (a function with
    its loops; a global; a trait implementation); each strongly connected component of the reference graph between
    nodes is one module."""
    mods: dict[str, str] = {}
    deps: dict[str, list[str]] = {}
    order: list[str] = []
    externals: list[str] = []
    for kind in ("Types", "Funs"):
        tmpl = gdir / f"{kind}External_Template.lean"
        if tmpl.exists():
            m = f"{prefix}.{kind}External"
            t = tmpl.read_text()
            externals += _DEF_RE.findall(t) if kind == "Funs" else []
            # unmodelled items are opaque constants, not axioms: nothing can be proved about them
            t = re.sub(r"^axiom ", "opaque ", t, flags=re.M)
            t = _header(t.splitlines(keepends=True), ["Aeneas"] + ([f"{prefix}.Types"] if kind == "Funs" else []))
            mods[m] = t
    types_mod = f"{prefix}.Types"
    types_text = (gdir / "Types.lean").read_text() if (gdir / "Types.lean").exists() else ""
    # floating-point types: Aeneas's library has no F32/F64 but its output names them (e.g. in a library trait such as
    # byteorder::ByteOrder): declared opaque, so the types module checks and float computations stay unmodelled (opaque
    # library functions, gap:external)
    texts = [types_text] + [(gdir / f).read_text() for f in ("Funs.lean", "FunsExternal_Template.lean")
                            if (gdir / f).exists()]
    floats = sorted({m for x in texts for m in re.findall(r"(?<![\w.])F(?:32|64)(?![\w.])", x)})
    if floats:
        m = f"{prefix}.TypesExternal"
        if m not in mods:
            mods[m] = _header(["module\n", "public import Aeneas\n", "@[expose] public section\n"], ["Aeneas"])
        mods[m] += ("\n/-- Floating-point types, not modelled by Aeneas's library: opaque (veriforch). -/\n"
                    + "".join(f"opaque {f} : Type\n" for f in floats))
    th, tns, tchunks, ttrail = split_lean(types_text)
    t_imports = ["Aeneas"] + ([f"{prefix}.TypesExternal"] if f"{prefix}.TypesExternal" in mods else [])
    if tns:
        mods[types_mod] = _header(th, t_imports) + f"namespace {tns}\n" + "".join(
            normalize_chunk(c["text"]) for c in tchunks) + f"end {tns}\n" + ttrail
    else:
        mods[types_mod] = _header(th or ["module\n", "public import Aeneas\n"], t_imports)
    if f"{prefix}.TypesExternal" in mods:
        order.append(f"{prefix}.TypesExternal")
        deps[f"{prefix}.TypesExternal"] = []
    order.append(types_mod)
    deps[types_mod] = [m for m in t_imports if m != "Aeneas"]
    # veriforch's support module (VerifOrch/Rust/Support.lean: `vo_bounds`, the meaning of the statements) is imported
    # by every function module, so every obligation has it and its cache key covers it
    mods[SUPPORT_MODULE] = SUPPORT_LEAN.read_text()
    order.insert(0, SUPPORT_MODULE)
    deps[SUPPORT_MODULE] = []
    base_imports = [types_mod, SUPPORT_MODULE]
    if f"{prefix}.FunsExternal" in mods:
        order.append(f"{prefix}.FunsExternal")
        deps[f"{prefix}.FunsExternal"] = [types_mod]
        base_imports.append(f"{prefix}.FunsExternal")
    funs_text = (gdir / "Funs.lean").read_text() if (gdir / "Funs.lean").exists() else ""
    fh, ns, chunks, ftrail = split_lean(funs_text)
    ns = ns or tns or (crate_ns or "")
    # nodes: one Rust item each (loops belong to their function); a mutual block joins its items
    node_of_path: dict[str, str] = {}
    node_chunks: dict[str, list[dict]] = {}
    for c in chunks:
        items = sorted({p for p, _, _ in c["paths"]}) or [f"_anon{len(node_chunks)}"]
        key = items[0]
        for p in items:
            key = node_of_path.get(p, key)
        for p in items:
            node_of_path[p] = key
        node_chunks.setdefault(key, []).append(c)
    def_node = {d: k for k, cs in node_chunks.items() for c in cs for d in c["defs"]}
    edges: dict[str, set[str]] = {}
    ext_used: dict[str, list[str]] = {}
    ext_set = set(externals)
    for k, cs in node_chunks.items():
        toks = set()
        for c in cs:
            toks |= _tokens(c["text"])
        toks |= {t[len(ns) + 1:] for t in toks if ns and t.startswith(ns + ".")}
        edges[k] = {def_node[t] for t in toks if t in def_node and def_node[t] != k}
        ext_used[k] = sorted(t for t in toks if t in ext_set)
    comps = _sccs(sorted(node_chunks), edges)
    mod_of_node: dict[str, str] = {}
    used_names: set[str] = set()
    for comp in comps:
        leaf = comp[0].split("::")[-1] if comp[0].count("::") else comp[0]
        nm = f"{prefix}.F_{_component(comp[0].split('::', 1)[-1] if '::' in comp[0] else comp[0])}"
        k = 2
        while nm in used_names:
            nm = f"{prefix}.F_{_component(leaf)}_{k}"
            k += 1
        used_names.add(nm)
        for n in comp:
            mod_of_node[n] = nm
    for comp in comps:
        m = mod_of_node[comp[0]]
        callee_mods = sorted({mod_of_node[e] for n in comp for e in edges[n]} - {m},
                             key=lambda x: order.index(x) if x in order else 0)
        imports = base_imports + callee_mods
        text = _header(fh, ["Aeneas"] + imports) + f"namespace {ns}\n" + "".join(
            normalize_chunk(c["text"]) for n in comp for c in node_chunks[n]) + f"end {ns}\n"
        mods[m] = text
        deps[m] = imports
        order.append(m)
    nodes = []
    for k, cs in node_chunks.items():
        # the item's own definition (not one of its loops): the chunk whose doc comment names the item without a kind
        main = [(c, sp) for c in cs for (p, kd, sp) in c["paths"] if p == k and not kd.startswith("loop")]
        nodes.append({"path": k, "module": mod_of_node[k], "defs": [d for c in cs for d in c["defs"]],
                      "main": (main[0][0]["defs"] or [None])[0] if main else None,
                      "span": main[0][1] if main else None, "text": "".join(normalize_chunk(c["text"]) for c in cs),
                      "callees": sorted(edges[k]), "externals": ext_used[k]})
    return {"modules": mods, "order": order, "deps": deps, "nodes": nodes, "externals": externals, "ns": ns,
            "types_module": types_mod, "types_chunks": [normalize_chunk(c["text"]) for c in tchunks]}


