_CFG_TEST_RE = re.compile(r"#!?\[cfg\(test\)\]")
_ATTR_RE = re.compile(r"^(?P<ind>[ \t]*)#\[(?P<a>test|should_panic|ignore)(?P<args>(?:\s*=\s*\"[^\"\n]*\"|\s*\([^\n]*?\))?)\]",
                      re.M)


def promote_tests(text: str) -> tuple[str, int]:
    """The rewrite of a source file that turns its tests into ordinary functions (line numbers unchanged)."""
    n = len(re.findall(r"^[ \t]*#\[test\]", text, re.M))
    text = _CFG_TEST_RE.sub("", text)
    text = _ATTR_RE.sub(lambda m: f'{m.group("ind")}#[doc = "vo:{m.group("a")}"]', text)
    return text, n


def _opt_path(target: Target, key: str) -> Path:
    """A target option naming a file: absolute, or relative to the target file's directory."""
    p = Path(target.extra[key])
    return p if p.is_absolute() else Path(target.extra.get("_target_dir", ".")) / p


def _toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k if re.fullmatch(r'[A-Za-z0-9_-]+', k) else json.dumps(k)} = {_toml_value(x)}"
                                for k, x in v.items()) + " }"
    raise TypeError(f"no TOML for {v!r}")


def _vendor_paths(target: Target) -> tuple[Path, Path]:
    """The pinned Cargo.lock and the vendored sources of the crate at `root`: `cargo_lock` / `vendor_dir`, or with
    `vendor_sets` the set of this revision's Cargo.toml, <vendor_sets>/<sha256 of root/Cargo.toml>/{Cargo.lock,vendor}
    (or <first 16 hex digits>/; one set per distinct manifest, e.g. tools/thrift_rsts/t3_vendor_sets.py: a revision
    range whose dependencies change builds every revision from its own lock)."""
    if target.extra.get("vendor_sets"):
        h = sha256((Path(target.root) / "Cargo.toml").read_bytes())
        d = _opt_path(target, "vendor_sets") / h[:16]
        if not d.is_dir():
            d = _opt_path(target, "vendor_sets") / h
        if not (d / "Cargo.lock").exists() or not (d / "vendor").is_dir():
            raise ValueError(f"no vendor set for Cargo.toml sha256 {h} in {_opt_path(target, 'vendor_sets')}")
        return d / "Cargo.lock", d / "vendor"
    return _opt_path(target, "cargo_lock"), _opt_path(target, "vendor_dir")


def _vendored_deps(target: Target, man: dict) -> dict:
    """[dependencies] of a vendored crate: its own, with the features of `dep_features` merged."""
    deps = dict(man.get("dependencies", {}))
    for name, feats in (target.extra.get("dep_features") or {}).items():
        if name not in deps:                         # an older revision without that dependency
            continue
        spec = deps[name]
        spec = {"version": spec} if isinstance(spec, str) else dict(spec)
        spec["features"] = sorted(set(spec.get("features", [])) | set(feats))
        deps[name] = spec
    return deps


def _cargo_manifest(target: Target) -> tuple[dict[str, bytes], str, str]:
    """The crate copy's files (relative path -> content), its crate name and its library root."""
    root = Path(target.root)
    mode = target.extra.get("rust_crate", "crate")
    files: dict[str, bytes] = {}
    if mode == "files":
        src_root = target.extra.get("rust_src_root", "src")
        crate = target.extra.get("crate_name") or _ident(target.name).lower()
        edition = str(target.extra.get("edition", "2021"))
        tree: dict = {}
        for s in target.sources:
            rel = Path(s).relative_to(src_root)
            if rel.suffix != ".rs" or rel.name in ("mod.rs", "lib.rs", "main.rs"):
                raise ValueError(f"rust_crate = 'files' takes plain module files, not {s}")
            node = tree
            for part in rel.parts[:-1]:
                node = node.setdefault(part, {})
            node[rel.stem] = None
            files[f"src/{rel.as_posix()}"] = (root / s).read_bytes()

        def mods(node: dict, ind: str) -> list[str]:
            out = []
            for k, v in sorted(node.items()):
                out += [f"{ind}pub mod {k};"] if v is None else [f"{ind}pub mod {k} {{"] + mods(v, ind + "    ") + [f"{ind}}}"]
            return out
        files["src/lib.rs"] = ("// crate made by veriforch from the target's module files\n"
                               + "\n".join(mods(tree, "")) + "\n").encode()
        lib = "src/lib.rs"
    else:
        man = tomllib.loads((root / "Cargo.toml").read_text())
        pkg = man.get("package", {})
        if (root / "build.rs").exists() or pkg.get("build"):
            raise ValueError("the crate has a build script (never run): use rust_crate = 'files'")
        if mode != "vendored" and (man.get("dependencies") or man.get("build-dependencies")):
            raise ValueError("the crate has dependencies (not fetched, not built): use rust_crate = 'files' or "
                             "'vendored'")
        if mode == "vendored" and man.get("build-dependencies"):
            raise ValueError("build-dependencies are not supported")
        libsec = man.get("lib", {})
        if libsec.get("proc-macro"):
            raise ValueError("procedural macro crates are not supported")
        crate = (libsec.get("name") or pkg.get("name", root.name)).replace("-", "_")
        edition = str(pkg.get("edition", "2015"))
        lib = libsec.get("path", "src/lib.rs")
        for f in sorted((root / "src").rglob("*")):
            if f.is_file():
                files[f.relative_to(root).as_posix()] = f.read_bytes()
        if lib not in files:
            raise ValueError(f"no library root {lib}")
        feats = man.get("features")
    toml = [f'[package]\nname = "{crate}"\nversion = "0.0.0"\nedition = "{edition}"\n', f'[lib]\npath = "{lib}"\n',
            "[workspace]\n"]
    if mode == "vendored":
        if pkg.get("rust-version"):                  # cargo's resolver picked the locked versions for it
            toml[0] += f'rust-version = "{pkg["rust-version"]}"\n'
        toml.append("[dependencies]\n" + "".join(f"{k} = {_toml_value(v)}\n"
                                                 for k, v in _vendored_deps(target, man).items()))
    if mode != "files" and feats:
        toml.append("[features]\n" + "".join(f"{k} = {json.dumps(v)}\n" for k, v in feats.items()))
    files["Cargo.toml"] = "\n".join(toml).encode()
    if mode == "vendored":
        lock, vendor = _vendor_paths(target)
        files["Cargo.lock"] = lock.read_bytes()
        files[".cargo/config.toml"] = (f'[source.crates-io]\nreplace-with = "vendored-sources"\n\n'
                                       f'[source.vendored-sources]\ndirectory = "{vendor}"\n\n'
                                       f'[net]\noffline = true\n').encode()
    return files, crate, lib


def _write_tree(dst: Path, files: dict[str, bytes]) -> None:
    for rel, data in files.items():
        p = dst / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_bytes() != data:
            p.write_bytes(data)


# -- Charon and Aeneas -------------------------------------------------------------------------------------------------

def _includes(target: Target) -> list[str]:
    """`charon_include`; for a vendored crate only the patterns whose crate this revision has: itself, core / alloc /
    std, or one of its dependencies (a range in which one dependency replaced another names both)."""
    pats = list(target.extra.get("charon_include") or [])
    man = Path(target.root) / "Cargo.toml"
    if target.extra.get("rust_crate") != "vendored" or not man.exists():
        return pats
    m = tomllib.loads(man.read_text())
    have = {k.replace("-", "_") for k in (m.get("dependencies") or {})} | {"core", "alloc", "std", "crate"}
    have.add(((m.get("lib") or {}).get("name") or m.get("package", {}).get("name", "")).replace("-", "_"))
    return [p for p in pats if p.split("::", 1)[0] in have]


def _charon_options(target: Target | None) -> tuple[list[str], list[str]]:
    """Charon options and cargo arguments of a target (none for a target without the options below)."""
    if target is None:
        return [], []
    opts: list[str] = []
    for pat in _includes(target):
        opts += ["--include", pat]
    if target.extra.get("aeneas_prune_file"):
        for e in prune_spec(target).get("opaque", []):
            opts += ["--opaque", e["pattern"]]
        # pruning removes items: in a hash-consed LLBC later items refer to values defined inside them
        opts.append("--no-dedup-serialized-ast")
    cargo = ["--locked", "--offline"] if target.extra.get("rust_crate") == "vendored" else []
    feats = list(target.extra.get("cargo_features") or [])
    man = Path(target.root) / "Cargo.toml"
    if feats and target.extra.get("rust_crate", "crate") in ("crate", "vendored") and man.exists():
        # only the features this revision's Cargo.toml defines (cargo rejects an undefined one)
        defined = tomllib.loads(man.read_text()).get("features") or {}
        feats = [f for f in feats if f in defined]
    if feats:
        cargo += ["--features", ",".join(feats)]
    return opts, cargo


def _rust_toolchain() -> str:
    return tomllib.loads((AENEAS / "bin" / "rust-toolchain").read_text())["toolchain"]["channel"]


def _bwrap(target: Target, work: Path, cdir: Path, cmd: list, env: dict) -> list:
    """`cmd` inside bubblewrap: every namespace unshared (no network), the system (/usr, /etc), the toolchain
    (~/.rustup, ~/.cargo/bin), Charon and the vendored sources read only, the rest of $HOME absent, the front-end work
    directory the only writable place (also HOME, CARGO_HOME, TMPDIR, the cargo target directory)."""
    home = Path.home()
    ro = [Path("/usr"), Path("/etc"), home / ".rustup", home / ".cargo" / "bin", AENEAS / "bin"]
    if target.extra.get("vendor_dir") or target.extra.get("vendor_sets"):
        ro.append(_vendor_paths(target)[1])
    for d in ("tmp", "home", "cargo_home"):
        (work / d).mkdir(parents=True, exist_ok=True)
    out = [BWRAP, "--unshare-all", "--die-with-parent", "--new-session", "--symlink", "usr/bin", "/bin",
           "--symlink", "usr/lib", "/lib", "--symlink", "usr/lib64", "/lib64", "--symlink", "usr/sbin", "/sbin",
           "--proc", "/proc", "--dev", "/dev", "--tmpfs", "/tmp"]
    for d in ro:
        out += ["--ro-bind", str(d), str(d)]
    out += ["--bind", str(work), str(work), "--chdir", str(cdir), "--clearenv"]
    full = {**{k: str(v) for k, v in env.items()}, "PATH": f"{home}/.cargo/bin:/usr/bin:/bin",
            "HOME": str(work / "home"), "RUSTUP_HOME": str(home / ".rustup"), "RUSTUP_TOOLCHAIN": _rust_toolchain(),
            "CARGO_HOME": str(work / "cargo_home"), "RAYON_NUM_THREADS": "1", "MALLOC_ARENA_MAX": "2"}
    for k, v in full.items():
        out += ["--setenv", k, v]
    return out + ["--"] + [str(c) for c in cmd]


def _charon(work: Path, cdir: Path, crate: str, target: Target | None = None) -> tuple[Path | None, str]:
    env = {"CARGO_TARGET_DIR": work / "target", "TMPDIR": work / "tmp", "CARGO_TERM_COLOR": "never", "NO_COLOR": "1",
           "CARGO_NET_OFFLINE": "true", "CARGO_INCREMENTAL": "0"}
    (work / "tmp").mkdir(parents=True, exist_ok=True)
    opts, cargo = _charon_options(target)
    cmd = [AENEAS / "bin" / "charon", "cargo", "--preset=aeneas", *opts, "--", "-j1", *cargo]
    if target is not None and target.extra.get("rust_sandbox") == "bwrap":
        cmd, env = _bwrap(target, work, cdir, cmd, env), None
    elif target is not None and target.extra.get("rust_crate") == "vendored":
        raise ValueError("rust_crate = 'vendored' runs dependency build scripts: it needs rust_sandbox = 'bwrap'")
    p = _job(cmd, cdir, mem_gib=64, timeout=1200, core_h=1.6, env=env, log=work / "logs" / f"charon_{cdir.name}.txt")
    out = _text(p.stdout)
    if _killed(p):
        raise RuntimeError(f"charon killed by the harness (exit {p.returncode})")
    llbc = cdir / f"{crate}.llbc"
    if not llbc.exists():
        blocks = re.split(r"\n(?=(?:error|warning)(?:\[\w+\])?: )", "\n" + out)
        errs = [b.strip() for b in blocks if b.lstrip().startswith("error")]
        return None, ("\n\n".join(errs) or out.strip()[-4000:])[:6000]
    return llbc, out


_AENEAS_ERR_RE = re.compile(r"^\[(?:\x1b\[[0-9;]*m)?Error(?:\x1b\[[0-9;]*m)?\s*\]\s*(?P<msg>.*?)$\n(?P<rest>(?:(?!^\[).*\n)*)",
                            re.M)


def _aeneas(work: Path, llbc: Path, subdir: str, namespace: str | None = None,
            log_name: str = "aeneas") -> tuple[Path, list[dict]]:
    """Aeneas on the LLBC; returns the directory of Types.lean/Funs.lean and its errors (message, file, line)."""
    cmd = [AENEAS / "bin" / "aeneas", "-backend", "lean", "-split-files", "-no-progress-bar", "-all-computable",
           "-max-recdepth", "100000", "-subdir", subdir, "-dest", work / "gen", llbc]
    if namespace:
        cmd[1:1] = ["-namespace", namespace]
    p = _job(cmd, work, mem_gib=48, timeout=2400, core_h=6.0, env={"TMPDIR": work / "tmp", "NO_COLOR": "1"},
             log=work / "logs" / f"{log_name}.txt")
    if _killed(p):
        raise RuntimeError(f"aeneas killed by the harness (exit {p.returncode})")
    out = _text(p.stdout)
    errors = []
    for m in _AENEAS_ERR_RE.finditer(out + "\n"):
        src = re.search(r"Source: '([^']+)', lines (\d+):\d+-(\d+):\d+", m.group("rest"))
        errors.append({"message": m.group("msg").strip()[:500], "file": src.group(1) if src else "",
                       "line": int(src.group(2)) if src else 0, "end": int(src.group(3)) if src else 0})
    gdir = work / "gen" / subdir
    if not (gdir / "Funs.lean").exists() and not (gdir / "Types.lean").exists():
        raise RuntimeError("Aeneas produced no Lean files:\n" + out.strip()[-4000:])
    return gdir, errors


