# -- jobs ----------------------------------------------------------------------------------------------------------

_JOB_SEQ = iter(range(1 << 62))
OUTPUT_HEAD, OUTPUT_TAIL = 256 << 10, 2 << 20      # bytes of a job's output read back (the rest stays on disk)


def _bounded(path: Path) -> bytes:
    """A job's output file, at most OUTPUT_HEAD + OUTPUT_TAIL bytes of it (a runaway job's output is never held in
    memory: a 33-min elaboration once printed enough to take the driver to 282 GB when it was captured whole)."""
    size = path.stat().st_size if path.exists() else 0
    with open(path, "rb") as f:
        if size <= OUTPUT_HEAD + OUTPUT_TAIL:
            return f.read()
        head = f.read(OUTPUT_HEAD)
        f.seek(size - OUTPUT_TAIL)
        return head + f"\n[... {size - OUTPUT_HEAD - OUTPUT_TAIL} bytes not read ...]\n".encode() + f.read()


def _job(cmd: list, cwd: Path, *, mem_gib: int, timeout: int, core_h: float, env: dict | None = None,
         log: Path | None = None) -> subprocess.CompletedProcess:
    """One job under scripts/run1.sh. Aeneas runs on several OCaml domains (CardDemo's CBACT04C: ~7 cores for
    4.3 min), so every job states its core-hour cap explicitly. Output goes to a file (`log`, or a temporary file in
    scratch/tmp) and only a bounded part of it is read back (stdout and stderr together, as `stdout`)."""
    full = [str(RUN1), "-t", str(timeout), "-m", str(mem_gib), "-c", f"{core_h:.2f}", "-l", str(GUARD_LOG), "--"]
    if env:
        full += ["env"] + [f"{k}={v}" for k, v in env.items()]
    full += [str(c) for c in cmd]
    tmpdir = VO_ROOT / "scratch" / "tmp"
    tmpdir.mkdir(parents=True, exist_ok=True)
    out = tmpdir / f"vo_rust_job_{os.getpid()}_{threading.get_ident()}_{next(_JOB_SEQ)}.txt"
    rc = 0
    with open(out, "wb") as f:
        f.write(f"$ {' '.join(full)}\n".encode())
        f.flush()
        try:
            rc = subprocess.run(full, cwd=cwd, stdin=subprocess.DEVNULL, stdout=f, stderr=subprocess.STDOUT,
                                timeout=timeout + 200).returncode
        except subprocess.TimeoutExpired:
            rc = 124
            f.write(b"\n[job timed out]\n")
    data = _bounded(out)
    if log is not None:
        log.parent.mkdir(parents=True, exist_ok=True)
        log.write_bytes(data + f"\nexit {rc}\n".encode())
    out.unlink()
    return subprocess.CompletedProcess(full, rc, data, b"")


def _text(b) -> str:
    s = b.decode("utf-8", "replace") if isinstance(b, bytes) else (b or "")
    return re.sub(r"\x1b\[[0-9;]*[A-Za-z]", "", s)


def _killed(p: subprocess.CompletedProcess) -> bool:
    return p.returncode in (124, 137) or b"[job timed out]" in (p.stdout or b"")[-200:]


# -- the pinned Lean side --------------------------------------------------------------------------------------------

def lean_dirs() -> list[str]:
    """LEAN_PATH entries of the pinned bridge: mathlib & co. (equiv-lean's builds, at Aeneas's manifest revisions),
    Aeneas's library, equiv-lean's Aeneas bridge."""
    man = json.loads((AENEAS / "lean" / "lake-manifest.json").read_text())
    theirs = {p["name"]: p.get("rev") for p in
              json.loads((LEAN_PACKAGES.parent.parent / "lake-manifest.json").read_text())["packages"]}
    dirs = []
    for p in man["packages"]:
        if theirs.get(p["name"]) != p.get("rev"):
            raise RuntimeError(f"Lean package {p['name']}: {LEAN_PACKAGES} has {theirs.get(p['name'])}, the pinned "
                               f"Aeneas library wants {p.get('rev')}")
        dirs.append(str(LEAN_PACKAGES / p["name"] / ".lake" / "build" / "lib" / "lean"))
    return dirs + [str(AENEAS / "lean" / ".lake" / "build" / "lib" / "lean"),
                   str(EQUIVLEAN / ".lake" / "build" / "lib" / "lean")]


_BRIDGE_LOCK = threading.Lock()


def build_bridge(eq_dir: Path = EQUIVLEAN) -> None:
    """Compile equiv-lean's Aeneas bridge (BRIDGE_MODULES) in the pinned copy, with `lean -o` in import order (no
    lake: Aeneas's lakefile would fetch mathlib). Done once; a stamp records the sources compiled."""
    out = eq_dir / ".lake" / "build" / "lib" / "lean"
    srcs = [eq_dir / (m.replace(".", "/") + ".lean") for m in BRIDGE_MODULES]
    want = sha256("".join(s.read_text() for s in srcs) + PIN)
    stamp = eq_dir / ".lake" / ".vo_bridge_built"
    if stamp.exists() and stamp.read_text() == want:
        return
    with _BRIDGE_LOCK:
        out.mkdir(parents=True, exist_ok=True)
        with open(eq_dir / ".lake" / ".vo_bridge.lock", "w") as lk:
            fcntl.flock(lk, fcntl.LOCK_EX)
            if stamp.exists() and stamp.read_text() == want:
                return
            lp = ":".join(lean_dirs()[:-1] + [str(out)])
            for m, src in zip(BRIDGE_MODULES, srcs):
                o = out / (m.replace(".", "/") + ".olean")
                o.parent.mkdir(parents=True, exist_ok=True)
                p = _job([LEAN_BIN, "-R", eq_dir, "-o", o, "-i", o.with_suffix(".ilean"), "-j", "1",
                          "-DElab.async=false", "-DautoImplicit=false", "-DrelaxedAutoImplicit=false", src], eq_dir,
                         mem_gib=64, timeout=1800, core_h=0.7, env={"LEAN_PATH": lp})
                if p.returncode != 0:
                    raise RuntimeError(f"equiv-lean bridge module {m} does not compile:\n{_text(p.stdout)[-3000:]}")
            stamp.write_text(want)


class RustLeanPackage(LeanPackage):
    """A package without Lake requirements: `lean` runs with an explicit LEAN_PATH (the package's own build
    directory, then `lean_dirs()`)."""

    def __init__(self, pkg_dir: Path, name: str, cache_dir: Path):
        super().__init__(pkg_dir, name, [], ["Gen", "VO", "VOEq", "VerifOrch"], cache_dir,
                         extra_lean_path=lean_dirs(), mem_gib=64)
        self.pin = PIN

    def ensure(self) -> None:
        self.dir.mkdir(parents=True, exist_ok=True)
        (self.dir / "lean-toolchain").write_text(TOOLCHAIN + "\n")
        build_bridge()

    # a `module` file (Aeneas's output, the support module) compiles to more than .olean/.ilean: the module system's
    # private and server parts and the compiler IR, which importers read; the cache keeps them with the .olean
    _EXTRA = (".olean.private", ".olean.server", ".ir", ".ir.sig")

    def check(self, mod: str, source: str, import_keys: dict[str, str] | None = None, **kw):
        olean = self.olean(mod)
        extras = [olean.with_name(olean.name[: -len(".olean")] + e) for e in self._EXTRA]
        key = self.key(source, import_keys or {})
        cdir = self.cache_dir / key[:2] / key
        is_module = re.search(r"^module\s*$", source[:3000], re.M) is not None
        hit = kw.get("use_cache", True) and (cdir / "result.json").exists()
        if hit and is_module and not (cdir / "m.olean.server").exists():
            kw["use_cache"] = hit = False          # an entry stored without the module parts: compile again
        if not hit:
            for x in extras:
                if x.exists():
                    x.unlink()
        res = super().check(mod, source, import_keys, **kw)
        if res.status == "cached":
            for e, x in zip(self._EXTRA, extras):
                c = cdir / ("m" + e)
                if c.exists():
                    shutil.copyfile(c, x)
                elif x.exists():
                    x.unlink()
        elif res.ok:
            suffix = f".{os.getpid()}.{threading.get_ident()}.tmp"
            for e, x in zip(self._EXTRA, extras):
                if x.exists():
                    tmp = cdir / ("m" + e + suffix)
                    shutil.copyfile(x, tmp)
                    tmp.replace(cdir / ("m" + e))
        return res

    def lean_path(self) -> str:
        return ":".join([str(self.dir / ".lake" / "build" / "lib" / "lean")] + self.extra_lean_path)

    def bridge_fingerprint(self) -> str:
        """sha256 over the compiled Aeneas library, equiv-lean's bridge modules and mathlib's root module (the cache
        key must follow what is on LEAN_PATH, not only the pin labels)."""
        if getattr(self, "_fp", None) is None:
            parts = []
            alib = AENEAS / "lean" / ".lake" / "build" / "lib" / "lean"
            for f in [alib / "Aeneas.olean"] + sorted((alib / "Aeneas").rglob("*.olean")):
                parts.append(f.relative_to(alib).as_posix() + ":" + sha256(f.read_bytes()))
            eq = EQUIVLEAN / ".lake" / "build" / "lib" / "lean"
            for m in BRIDGE_MODULES:
                f = eq / (m.replace(".", "/") + ".olean")
                parts.append(m + ":" + (sha256(f.read_bytes()) if f.exists() else "missing"))
            ml = LEAN_PACKAGES / "mathlib" / ".lake" / "build" / "lib" / "lean" / "Mathlib.olean"
            parts.append("Mathlib:" + (sha256(ml.read_bytes()) if ml.exists() else "missing"))
            self._fp = sha256("|".join(parts))
        return self._fp


def lean_package(run_dir: Path, revision: str) -> RustLeanPackage:
    # module names carry no revision, so each revision has its own package directory (compiled modules come back
    # from the shared content-addressed cache)
    return RustLeanPackage(run_dir / "lean_rust_rev" / _ident(revision), "vo_" + _ident(run_dir.name),
                           run_dir / "cache" / "olean")


