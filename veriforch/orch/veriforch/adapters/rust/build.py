"""Rust build: a cargo crate -> Charon (LLBC) -> Aeneas (Lean) -> units, call graph, one Lean module per function.

The crate is copied into the run directory and built there, never in place, and only crates without build scripts,
procedural macros or dependencies are accepted (a target's own code is compiled, as for C; nothing of it runs).
Tests are promoted by a rewrite of the copy that keeps every line where it was: `#[cfg(test)]` is removed, so test
modules become ordinary modules, and `#[test]` / `#[should_panic]` / `#[ignore]` become the doc attributes
`vo:test` / `vo:should_panic` / `vo:ignore`, which Charon keeps in the LLBC. A test function is therefore an ordinary
function of the crate (also one generated by `macro_rules!`), recognised by its attribute.

Charon (`--preset=aeneas`) gives the LLBC: the crate's functions with their spans, and every call (the call graph).
Aeneas translates it to Lean (`-split-files`: Types.lean, Funs.lean). Funs.lean is split into one module per
function (per cycle of definitions), importing the modules of the definitions it uses. Module names carry no
revision and each revision has its own package directory (as cir --modular), so an unchanged function, whose callees
are unchanged, has byte-identical Lean inputs in every revision and its compiled proof comes back from the cache.

Functions Aeneas does not model (Funs/TypesExternal_Template.lean) are declared `opaque`, not as axioms: a proof can
then use nothing about them, and every unit calling one is a gap (`gap:external:<names>`).

Target options (`extra`): `rust_crate = "crate"` (default: the crate at `root`) or `"files"` (a crate made of the
listed `sources`, which mirror their paths below `rust_src_root`, default "src"; `crate_name`, `edition`) or
`"vendored"` (the crate at `root` with its crates.io dependencies, pinned by `cargo_lock` and read from `vendor_dir`,
a `cargo vendor` directory: vendoring downloads sources and runs nothing; `dep_features` merges features into
dependencies, e.g. a dev-dependency feature the promoted tests need; `cargo_features` are enabled where the
revision's Cargo.toml defines them; `vendor_sets` instead of `cargo_lock`/`vendor_dir`: one lock and vendor directory
per sha256 of the revision's Cargo.toml, for a revision range whose dependencies change; `charon_include` patterns of
a crate the revision does not depend on are dropped).
`rust_sandbox = "bwrap"`: Charon runs inside bubblewrap (no network, read-only system, toolchain and vendored sources,
writable only the front-end work directory); dependency build scripts run during Charon, so a crate with
dependencies is built only this way. `charon_include`: name patterns of dependency items whose bodies Charon
translates (they are opaque otherwise), e.g. ["varint_rs"].
`aeneas_prune_file`: the items on which Aeneas aborts the whole crate (an uncaught exception, no Lean file at all),
found by tools/thrift_rsts/triage_rs.py, and how they are kept out (`prune_llbc`): `dyn_trait_methods = "prune"`
(trait methods with a dyn type in their signature are dropped, see prune_dyn_trait_methods), `rename` (generated
names for items whose names clash, as `#[charon::rename]` would give them), `mixed_groups = "split"` (Aeneas
stops analysing functions at the first mixed declaration group, see split_mixed_groups), `opaque` (Charon `--opaque`:
functions whose bodies reach an item Aeneas cannot take, e.g. core::str::pattern::Pattern), `dyn_fields = "opaque"`
(every field of a type declaration whose type contains a `dyn Trait` gets the opaque type `vo_dyn::DynValue`: Aeneas
fails a type with a dyn field and then aborts on every function that builds a value of it), `pruned` (trait
declarations whose methods have dyn types in their signatures lose those methods, in every impl too; impl methods and
functions are removed). Every removed or opaque function stays a unit, `gap:aeneas-abort:<reason>`, and keeps its
callers' call-graph edges (units and calls come from the unpruned LLBC).
"""
