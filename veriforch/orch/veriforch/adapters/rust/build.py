def _frontend(target: Target, run_dir: Path, subdir: str) -> dict:
    """Copy, Charon, Aeneas for one crate content (cached by content: a later build of the same tree, e.g. one
    `vo verify --only` per unit, or both CI steps of one revision, reuses it)."""
    files, crate, lib = _cargo_manifest(target)
    promoted = {}
    n_tests = 0
    for rel, data in files.items():
        if rel.endswith(".rs"):
            t, n = promote_tests(data.decode("utf-8", "replace"))
            promoted[rel] = t.encode()
            n_tests += n
    # the front-end options of a target (none: the key of a target without them is unchanged)
    fopts = {k: target.extra[k] for k in ("rust_sandbox", "cargo_features", "charon_include") if target.extra.get(k)}
    if target.extra.get("aeneas_prune_file"):
        fopts["prune"] = prune_spec(target)
    key = sha256(json.dumps([FRONTEND_VERSION, PIN, subdir, crate, sorted((k, sha256(v)) for k, v in files.items())]
                            + ([fopts] if fopts else [])))
    work = run_dir / "rust_fe" / key[:20]
    done = work / "frontend.json"
    if done.exists():
        return json.loads(done.read_text())
    work.mkdir(parents=True, exist_ok=True)
    info: dict = {"crate": crate, "lib": lib, "work": str(work), "rust_tests": n_tests, "test_build": "promoted"}
    cdir = work / "crate"
    _write_tree(cdir, {**files, **promoted})
    llbc, out = _charon(work, cdir, crate, target)
    if llbc is None and n_tests:
        # the test code does not compile as library code (e.g. it uses dev-dependencies): tests become gaps
        info["test_build"] = "failed: " + out[:1500]
        cdir = work / "crate_notests"
        _write_tree(cdir, files)
        llbc, out = _charon(work, cdir, crate, target)
    if llbc is None:
        raise RuntimeError("Charon (Rust to LLBC) rejects the crate:\n" + out)
    info["charon_warnings"] = len(re.findall(r"^warning", out, re.M))
    info["charon_errors"] = [b.strip()[:800] for b in re.split(r"\n(?=(?:error|warning)(?:\[\w+\])?: )", "\n" + out)
                             if b.lstrip().startswith("error")][:20]
    spec = prune_spec(target)
    if (spec.get("pruned") or spec.get("dyn_fields") or spec.get("mixed_groups") or spec.get("dyn_trait_methods")
            or spec.get("rename")):
        # what makes Aeneas abort the whole crate is kept out of the LLBC it reads (prune_llbc); the unpruned LLBC stays
        # for the units and the call graph
        d = json.loads(llbc.read_text())
        removed = prune_llbc(d, spec)
        pl = llbc.with_name(llbc.stem + ".pruned.llbc")
        pl.write_text(json.dumps(d))
        info.update({"llbc_unpruned": str(llbc), "pruned_functions": {str(k): v for k, v in removed.items()},
                     "opaque_dyn_fields": spec.get("_changed_fields", []),
                     "split_mixed_groups": spec.get("_split_groups", []),
                     "skipped_prune_entries": spec.get("_skipped_entries", [])})
        (work / "logs").mkdir(parents=True, exist_ok=True)
        (work / "logs" / "pruned.json").write_text(json.dumps(
            {"removed_functions": info["pruned_functions"], "opaque_dyn_fields": info["opaque_dyn_fields"],
             "split_mixed_groups": info["split_mixed_groups"], "skipped_prune_entries": info["skipped_prune_entries"],
             "opaque_functions": [e["pattern"] for e in spec.get("opaque", [])]}, indent=1))
        llbc = pl
    gdir, aerr = _aeneas(work, llbc, subdir)
    info.update({"llbc": str(llbc), "gen_dir": str(gdir), "aeneas_errors": aerr, "crate_dir": str(cdir)})
    tmp = done.with_name(done.name + f".{os.getpid()}.tmp")
    tmp.write_text(json.dumps(info, indent=1))
    tmp.replace(done)
    return info


def _check_generated(pkg: RustLeanPackage, sp: dict, jobs: int, log=print) -> tuple[dict[str, str], dict[str, str]]:
    """Check the split modules level by level (each level in parallel). Returns (module -> cache key, module ->
    error) — a module whose import failed is not checked."""
    keys: dict[str, str] = {}
    failed: dict[str, str] = {}
    left = [m for m in sp["order"]]
    lock = threading.Lock()

    def one(m: str) -> None:
        res = pkg.check(m, sp["modules"][m], {d: keys[d] for d in sp["deps"][m]}, timeout=900)
        with lock:
            if res.ok:
                keys[m] = res.cache_key
            else:
                failed[m] = "; ".join((res.errors or res.goals or [res.status])[:2])[:600]
    while left:
        while True:                     # everything importing a failed module fails, transitively
            bad = [m for m in left if any(d in failed for d in sp["deps"][m])]
            if not bad:
                break
            for m in bad:
                failed[m] = "imports a module that does not check: " + ", ".join(d for d in sp["deps"][m]
                                                                                if d in failed)
            left = [m for m in left if m not in bad]
        ready = [m for m in left if all(d in keys for d in sp["deps"][m])]
        if not ready:
            break
        with ThreadPoolExecutor(max_workers=max(1, jobs)) as ex:
            for f in [ex.submit(one, m) for m in ready]:
                f.result()
        left = [m for m in left if m not in ready]
    for m in left:
        failed[m] = "not checked: its imports never became available"
    return keys, failed


def build(target: Target, variant: Variant, run_dir: Path) -> Build:
    vdir = run_dir / target.version / variant.name
    vdir.mkdir(parents=True, exist_ok=True)
    root = Path(target.root)
    crate_ident = _ident(target.extra.get("crate_name") or target.name).capitalize()
    prefix = f"Gen.{_ident(variant.name)}.{crate_ident}"
    fe = _frontend(target, run_dir, prefix.replace(".", "/"))
    # with pruning: functions and calls from the unpruned LLBC (a removed function stays a unit, and its callers keep
    # their edges to it)
    llfuns, llinfo = llbc_functions(Path(fe.get("llbc_unpruned") or fe["llbc"]))
    pruned = {int(k): v for k, v in (fe.get("pruned_functions") or {}).items()}
    opaque = {e["pattern"]: e for e in prune_spec(target).get("opaque", [])}
    sp = split_modules(Path(fe["gen_dir"]), prefix)
    pkg = lean_package(run_dir, target.version)
    pkg.ensure()
    for m, text in sp["modules"].items():
        p = pkg.src(m)
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
    keys, failed = _check_generated(pkg, sp, int(os.environ.get("VO_RUST_GEN_JOBS", "3")))
    ns = sp["ns"]
    # files mode: copy paths are below src/, the target's paths below rust_src_root
    src_root = target.extra.get("rust_src_root", "src") if target.extra.get("rust_crate") == "files" else "src"

    def orig(file: str) -> str:
        return src_root + file[3:] if file.startswith("src/") and src_root != "src" else file
    # LLBC function -> Lean definition group: by Rust path (Charon and Aeneas print plain paths alike), else by span
    # (impl blocks print differently; a span shared by several functions, e.g. macro-generated tests, is not used)
    by_path = {n["path"]: n for n in sp["nodes"] if n["main"]}
    spans: dict = {}
    for n in sp["nodes"]:
        if n["main"] and n["span"]:
            spans.setdefault((n["span"][0], n["span"][1], n["span"][2]), []).append(n)
    node_of_fun: dict[int, dict] = {}
    for f in llfuns:
        n = by_path.get(f["path"])
        if n is None:
            cand = spans.get((f["file"], f["line"], f["col"]), [])
            if len(cand) > 1:          # a function and its FnOnce shim share the span: the last path component decides
                last = f["path"].rsplit("::", 1)[-1]
                cand = [c for c in cand if c["path"].rsplit("::", 1)[-1] == last]
            n = cand[0] if len(cand) == 1 else None
        if n is not None:
            node_of_fun[f["id"]] = n
    unit_name: dict[int, str] = {}
    for f in llfuns:
        n = node_of_fun.get(f["id"])
        unit_name[f["id"]] = n["main"] if n is not None else f["path"].split("::", 1)[-1].replace("::", ".")
        if n is None and (f["id"] in pruned or f["path"] in opaque) and "{" in f["path"]:
            unit_name[f["id"]] += f"@{f['file']}:{f['line']}"         # an impl's method: the path is not unique
    # a unit without a Lean definition is named after its Rust path, which repeats for methods of impls in one module
    # (`errors.{impl}.from`): those names get the definition's place
    counts: dict[str, int] = {}
    for v in unit_name.values():
        counts[v] = counts.get(v, 0) + 1
    for f in llfuns:
        if node_of_fun.get(f["id"]) is None and counts[unit_name[f["id"]]] > 1:
            unit_name[f["id"]] += f"@{f['file']}:{f['line']}"
    gone = {unit_name[f["id"]] for f in llfuns if f["id"] in pruned or f["path"] in opaque}
    types = {}
    for c in sp["types_chunks"]:
        for d in _DEF_RE.findall(c):
            types[d] = c
    units: list[Unit] = []
    unit_module: dict[str, str] = {}
    mismatches = []
    aerr = fe.get("aeneas_errors", [])
    src_cache: dict[str, list[str]] = {}
    globals_ = {f["id"] for f in llfuns if f["global"]}
    global_nodes = {node_of_fun[i]["path"] for i in globals_ if i in node_of_fun}
    for f in llfuns:
        if f["global"] or "{" in f["path"].split("::")[-1]:
            continue                                # constants, closures and promoted values belong to their item
        if not f["has_body"] and f["path"] not in opaque:
            continue
        name = unit_name[f["id"]]
        n = node_of_fun.get(f["id"])
        is_test = "vo:test" in f["attrs"]
        kind = "test" if is_test else (("api" if name in target.entry else "internal") if target.entry
                                       else ("api" if f["public"] else "internal"))
        callees = [unit_name[c] for c in f["local_callees"] if c in unit_name and unit_name[c] != name
                   and c not in globals_]
        rel = orig(f["file"])
        lines = src_cache.setdefault(rel, (root / rel).read_text(errors="replace").splitlines()
                                     if (root / rel).exists() else [])
        source = "\n".join(lines[max(0, f["line"] - 1): f["end"]])
        sig = {"rust": f["path"], "lib_callees": f["lib_callees"]}
        if is_test:
            sig["should_panic"] = "vo:should_panic" in f["attrs"]
            sig["ignored"] = "vo:ignore" in f["attrs"]
        if n is None:
            err = next((e["message"] for e in aerr if e["file"] == f["file"] and e["line"] <= f["line"] <= e["end"]
                        or e["file"] == f["file"] and f["line"] <= e["line"] <= f["end"]), None)
            scope = ("gap:charon:" + "; ".join(fe.get("charon_errors", [])[:1])[:300] if f["has_errors"] else
                     "gap:aeneas:" + (err or "no Lean definition generated"))
            if is_test and fe.get("test_build", "promoted") != "promoted":
                scope = "gap:test:the test code does not compile as library code"
            if f["id"] in pruned:
                scope = f"gap:aeneas-abort:{pruned[f['id']]}"
            elif f["path"] in opaque:
                scope = f"gap:aeneas-abort:{opaque[f['path']].get('reason', 'opaque')}"
            body_hash = sha256(source)[:16]
            lean = f"{ns}.{name}"
        else:
            if n["module"] in failed:
                scope = "gap:lean:" + failed[n["module"]]
            elif _SORRY_RE.search(re.sub(r"/--.*?-/", "", n["text"], flags=re.S)):
                # Aeneas writes `sorry` for a body it could not translate ("Ignoring the body of ..."): it checks, but
                # nothing is known about the function
                err = next((e["message"] for e in aerr if e["file"] == f["file"] and (e["line"] <= f["line"] <= e["end"]
                            or f["line"] <= e["line"] <= f["end"]) and not e["message"].startswith("Ignoring")), None)
                scope = "gap:aeneas:" + (err or "body not translated (sorry)")
            elif n["externals"]:
                scope = "gap:external:" + ",".join(n["externals"][:6])
            else:
                scope = "in_scope"
            lean_callees = sorted({unit_name[g["id"]] for g in llfuns if node_of_fun.get(g["id"]) is not None
                                   and node_of_fun[g["id"]]["path"] in n["callees"]
                                   and node_of_fun[g["id"]]["path"] not in global_nodes} - {name})
            if sorted(set(callees) - gone) != lean_callees:
                mismatches.append({"unit": name, "charon": sorted(set(callees)), "lean": lean_callees})
                callees = sorted(set(callees) | set(lean_callees))
            ttext = "".join(types[t] for t in sorted(_tokens(n["text"]) & set(types)))
            body_hash = sha256(n["text"] + "\n" + ttext)[:16]
            lean = f"{ns}.{name}"
            unit_module[name] = n["module"]
            sig.update({"lean": lean, "defs": [f"{ns}.{d}" for d in n["defs"]], "module": n["module"],
                        "binders": _binders(n["text"], name), "ret": _ret(n["text"], name)})
        units.append(Unit(name=name, sym=lean, lean_decl=lean, kind=kind, signature=sig,
                          callees=sorted(dict.fromkeys(callees)), scope=scope,
                          loc=f"{root / rel}:{f['line']}", body_hash=body_hash, source=source))
    # a test that reaches a function calling an unmodelled library item (an opaque stand-in) can be proved neither by
    # symbolic execution nor by evaluation: a gap, named after the first such function it reaches
    by_name = {u.name: u for u in units}
    for u in units:
        if u.kind != "test" or not u.in_scope:
            continue
        seen, todo, hit = set(), list(u.callees), None
        while todo and hit is None:
            c = by_name.get(todo.pop())
            if c is None or c.name in seen:
                continue
            seen.add(c.name)
            if not c.in_scope:
                hit = c
            todo += c.callees
        if hit is not None:
            u.scope = f"gap:reaches:{hit.name} ({hit.scope})"[:300]
    ok_order = [m for m in sp["order"] if m in keys]
    gen_mod = f"{prefix}.Funs"
    node_mods = [m for m in ok_order if m.startswith(prefix + ".F_")]
    top = _header(["module\n", "public import Aeneas\n", "@[expose] public section\n"],
                  ["Aeneas"] + [m for m in ok_order if not m.endswith("External") and m != SUPPORT_MODULE])
    pkg.src(gen_mod).write_text(top)
    info = {"gen_module": gen_mod, "gen_ns": ns, "types_module": sp["types_module"], "ns": f"VO.{_ident(variant.name)}",
            "gen_order": ok_order + [gen_mod],
            "gen_deps": {**{m: sp["deps"][m] for m in ok_order}, gen_mod: ok_order},
            "unit_module": unit_module, "crate": fe["crate"], "crate_ns": ns, "prefix": prefix,
            "llbc": fe["llbc"], "gen_dir": fe["gen_dir"], "frontend": fe["work"], "rust_tests": fe["rust_tests"],
            "test_build": fe["test_build"], "aeneas_errors": aerr, "charon_errors": fe.get("charon_errors", []),
            "externals": sp["externals"], "failed_modules": failed, "callgraph_mismatch": mismatches,
            "pruned_functions": len(pruned), "opaque_functions": sorted(opaque),
            "opaque_dyn_fields": fe.get("opaque_dyn_fields", []), "split_mixed_groups": fe.get("split_mixed_groups", []),
            "charon_version": llinfo.get("charon_version"), "node_modules": len(node_mods)}
    (vdir / "rust_build.json").write_text(json.dumps({k: v for k, v in info.items() if k != "gen_deps"}, indent=1))
    b = Build(target=target, variant=variant, dir=vdir, pkg=pkg, units=units, info=info)
    b.gen_modules.update(keys)
    return b


def _decl_head(text: str, name: str) -> str | None:
    """`def <name> <binders> : <type> :=` of a definition in a chunk (binders may span lines)."""
    m = re.search(rf"^def\s+{re.escape(name)}(?=[\s(:{{\[])(.*?):=", text, re.S | re.M)
    return m.group(1) if m else None


def _binders(text: str, name: str) -> list[dict]:
    """The binders of `def <name>`: [{"text": "(x : Std.U32)", "names": ["x"], "type": "Std.U32", "explicit": bool}]
    (implicit and instance binders are a generic function's type and trait parameters)."""
    head = _decl_head(text, name)
    if head is None:
        return []
    binders, depth, cur = [], 0, ""
    for ch in head:
        if ch in "([{⦃" and depth == 0:
            cur, depth = ch, 1
        elif depth:
            cur += ch
            if ch in "([{⦃":
                depth += 1
            elif ch in ")]}⦄":
                depth -= 1
                if depth == 0:
                    binders.append(cur)
                    cur = ""
        elif ch == ":":
            break
    out = []
    for b in binders:
        inner = b[1:-1]
        names, ty = (inner.split(":", 1) + [""])[:2] if ":" in inner else ("", inner)
        out.append({"text": b, "names": names.split(), "type": " ".join(ty.split()), "explicit": b[0] == "("})
    return out


def _ret(text: str, name: str) -> str:
    head = _decl_head(text, name)
    if head is None:
        return ""
    depth = 0
    for i, ch in enumerate(head):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == ":" and depth == 0:
            return " ".join(head[i + 1:].split())
    return ""
