"""Pre-registration H, part one: generate the UB locator, a copy of the pinned cirlean's interpreter that tags each
undefined-behaviour result with where it happened. It only locates: the verdict is the pinned runner's (vo-cirrun), and
a located run counts only if its message, with the tags removed, equals the pinned runner's message.

    python3 -I -B h_locator_gen.py EVAL_LEAN VOCIRRUN_LEAN OUT_LEAN

EVAL_LEAN: CIR/Semantics/Eval.lean of the pinned cirlean; VOCIRRUN_LEAN: veriforch's tools/vo_cirrun/VoCirRun.lean (both
sha256-checked, so a different pin or runner stops this script). OUT_LEAN: the locator's Lean source:
- cirlean's interpreter mutual block (`evalOps` ... `evalCall`), copied verbatim with three mechanical edits: the twelve
  functions are renamed h<Name> and are `partial def`s (compiled evaluation, as cirrun runs them; `partial_fixpoint`
  only matters to proofs); a call's result passes through `annotCall`, which on UB prepends
  `⟦call <fn|model|extern|unknown> <callee> @<line>:<col>⟧` (the call site); a loop's result passes through `annotLoop`,
  which on UB prepends `⟦loop @<line>:<col>⟧`. Unwinding thus leaves a backtrace, outermost first, before the message;
  every other result is unchanged.
- vo-cirrun's argument handling, linking and printing, copied verbatim, with `evalCall` replaced by `hEvalCall`.
Lines and columns are those of the call or loop in the source file of the function that contains it (cirlean's Loc
has no file name; the enclosing function's symbol names its translation unit).
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

EVAL_SHA256 = "9b593b6d4b63967bcaa75af51586e274fbc430d3980d85aee6259f12ce18d83f"     # cirlean ffab71e
VOCIRRUN_SHA256 = "7b99affa761ab23e0fdc6d43448381798c63cc3d5eb6c0f9c23e6a05fdc8645f"
FUNCS = ["evalOps", "evalRegion", "evalBlock", "evalOp", "evalCases", "evalIterCleanup", "evalForStep", "evalFor",
         "evalWhile", "evalDoCond", "evalDo", "evalCall"]

PRELUDE = '''import CIR

/-! H locator (generated by veriforch scripts/h_locator_gen.py from the pinned cirlean's CIR/Semantics/Eval.lean and
veriforch's tools/vo_cirrun/VoCirRun.lean; see that script). Do not edit. -/

namespace CIR

def hLocStr (l : Loc) : String := toString l.line ++ ":" ++ toString l.col

/-- On UB, prepend the call site and the kind of the callee. -/
def annotCall {α : Type} (ctx : Ctx) (sym : String) (l : Loc) (r : Res α) : Res α :=
  match r with
  | .ub msg =>
    let kind := match ctx.mod.findFunc? sym with
      | some fd => if fd.model.isSome then "model" else if fd.body.isNone then "extern" else "fn"
      | none => "unknown"
    .ub ("⟦call " ++ kind ++ " " ++ sym ++ " @" ++ hLocStr l ++ "⟧" ++ msg)
  | r => r

/-- On UB, prepend the loop's position. -/
def annotLoop {α : Type} (l : Loc) (r : Res α) : Res α :=
  match r with
  | .ub msg => .ub ("⟦loop @" ++ hLocStr l ++ "⟧" ++ msg)
  | r => r

'''


def sub1(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(f"expected exactly one occurrence of {old!r}, found {text.count(old)}")
    return text.replace(old, new)


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    ev, vr, out = Path(argv[1]), Path(argv[2]), Path(argv[3])
    for p, want in ((ev, EVAL_SHA256), (vr, VOCIRRUN_SHA256)):
        got = hashlib.sha256(p.read_bytes()).hexdigest()
        if got != want:
            raise SystemExit(f"{p}: sha256 {got}, the generator is for {want}")
    lines = ev.read_text().splitlines(keepends=True)
    starts = [i for i, ln in enumerate(lines) if ln == "mutual\n"]
    if len(starts) != 1:
        raise SystemExit(f"expected one mutual block in {ev}, found {len(starts)}")
    s = starts[0]
    e = next(i for i in range(s + 1, len(lines)) if lines[i] == "end\n")
    block = "".join(lines[s:e + 1])
    if block.count("partial_fixpoint\n") != len(FUNCS):
        raise SystemExit("unexpected number of partial_fixpoint definitions")
    block = block.replace("partial_fixpoint\n", "")
    for f in FUNCS:
        if not re.search(rf"^def {f}\b", block, re.M):
            raise SystemExit(f"no definition of {f} in the block")
        block = re.sub(rf"\b{f}\b", "h" + f[0].upper() + f[1:], block)
    block = re.sub(r"^def h", "partial def h", block, flags=re.M)
    block = sub1(block, "  | .call _ res callee args argTys _ _ => do\n",
                 "  | .call loc res callee args argTys _ _ => do\n")
    block = sub1(block, "    let (e, m) ← hEvalCall ctx sym vs σ.mem\n",
                 "    let (e, m) ← annotCall ctx sym loc (hEvalCall ctx sym vs σ.mem)\n")
    block = sub1(block, "  | .forOp _ c b s cl => hEvalFor ctx c b s cl σ\n",
                 "  | .forOp loc c b s cl => annotLoop loc (hEvalFor ctx c b s cl σ)\n")
    block = sub1(block, "  | .whileOp _ c b cl => hEvalWhile ctx c b cl σ\n",
                 "  | .whileOp loc c b cl => annotLoop loc (hEvalWhile ctx c b cl σ)\n")
    block = sub1(block, "  | .doWhileOp _ b c => hEvalDo ctx b c σ\n",
                 "  | .doWhileOp loc b c => annotLoop loc (hEvalDo ctx b c σ)\n")
    vtext = vr.read_text()
    k = vtext.index("\nopen CIR CIR.Frontend\n")
    runner = vtext[k + 1:]
    runner = sub1(runner, "    let r := evalCall ctx f.sym vals.toList mem\n",
                  "    let r := hEvalCall ctx f.sym vals.toList mem\n")
    runner = runner.replace("vo-cirrun", "h-locate")
    out.write_text(PRELUDE + block + "\nend CIR\n\n" + runner)
    print(f"{out}\t{hashlib.sha256(out.read_bytes()).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
